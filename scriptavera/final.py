"""The final version.

Only now, after the draft has been read three times and the author has decided on everything mathematical:

  1. the author's decisions are carried out;
  2. every part is copy-edited once (grammar, tone, consistency) together with the referee's points on
     presentation; an edit is kept only if it changed wording and nothing else;
  3. the typography is corrected by rule (punctuation after displayed formulas, ties, spacing);
  4. citations are checked, the abstract is written to the journal's length, and titles are suggested last;
  5. the LaTeX file is generated by code in the journal's template and compiled;
  6. the author chooses the title, approves the introduction and chooses what it cites (the last step).

`build_outputs` is pure assembly and calls no model, so the author's later edits and a change of journal rebuild
everything without rewriting anything.
"""

