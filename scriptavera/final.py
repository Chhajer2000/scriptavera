# ------------------------------------------------------------------ title

_NOT_A_TITLE = re.compile(r"^(?:open\s+problem|problem|question|exercise|classify|find|determine|prove|show|compute|let|"
                          r"describe|give|decide|study|consider|is|are|does|do|can|what|which|how|why|when)\b", re.I)


def good_title(t: str) -> bool:
    """A title names a subject. It is not a task, a question or a sentence."""
    t = t.strip()
    words = re.sub(r"\$[^$]*\$", "X", t).split()
    return bool(t) and 2 <= len(words) <= 16 and not _NOT_A_TITLE.match(t) and not t.endswith(("?", ":", ".")) \
        and not check_balance(t)


# -------------------------------------------------------------- assembly

def fig_url_for(p: Project, embed: bool):
    def url(fid: str, mode: str) -> str:
        f = figure_file(p, fid, mode)
        if not embed:
            return f"/api/projects/{p.id}/figure/{fid}?kind={mode}&v={int(f.stat().st_mtime) if f.exists() else 0}"
        if not f.exists():
            return ""
        return f"data:image/{'png' if mode == 'tikz' else 'jpeg'};base64," + base64.b64encode(f.read_bytes()).decode()
    return url


def build_outputs(p: Project, paper: dict, compile_now: bool = True) -> dict:
    """Pure assembly: references, journal template, HTML, LaTeX, PDF, zip. No model is called."""
    meta = p.state.get("meta", {})
    prof = journals.profile(meta.get("journal"))
    paper["profile"] = prof
    paper["journal"] = meta.get("journal")
    paper["statements"] = meta.get("statements") or {}
    paper["cite_software"] = bool(meta.get("cite_software"))    # the declaration of Scriptavera, and its reference
    library = {x["key"]: x for x in p.load("library", [])}

    full = paper.get("keywords_full") or paper.get("keywords") or []
    paper["keywords_full"] = full
    paper["keywords"] = full[:prof["keywords_max"]] if prof.get("keywords_max") else list(full)

    cited = [k for k in cited_keys([paper.get("intro", "")] + [b.get("text", "") + " " + (b.get("title") or "") for b in paper["blocks"]])
             if k in library]
    refs = [library[k] for k in cited]
    if paper["cite_software"]:
        refs.append(paperlib.software_reference())             # cited last, in the declaration before the references
    if prof.get("ref_order") == "alphabetical":
        refs.sort(key=lambda x: ((x["authors"][0]["family"] if x.get("authors") else "zzz").lower(), x.get("year") or 0))
    paper["refs"] = [{k: x.get(k) for k in ("key", "title", "authors", "year", "venue", "journal_ref", "volume", "issue", "pages",
                                            "doi", "arxiv", "zbl", "url", "fulltext", "verdict", "kind")} for x in refs]
    paper["uncited"] = [{"key": x["key"], "title": x["title"], "year": x.get("year"), "verdict": x.get("verdict")}
                        for x in library.values() if x.get("read") and x["key"] not in cited]
    paper["html"] = paperlib.render_html(paper, refs, fig_url_for(p, False))
    paper["lint"] = paperlib.lint(paper)
    paper["audit"] = fidelity.audit(audit_pages(approved_pages(p)), paperlib.blocks_to_latex(paper["blocks"]),
                                    waived=paper.get("waived", ""), approved=paper.get("approved_text", ""))
    out = p.dir / "out"
    out.mkdir(exist_ok=True)
    extra: dict[str, bytes] = {}
    typed = p.load("typed") or {}
    paper["source_preamble"], paper["katex_macros"] = typed.get("preamble", []), typed.get("katex", {})
    src_dir = p.dir / "source_files"
    if src_dir.exists():                        # figures and files of typed notes, where \includegraphics finds them
        for f in src_dir.rglob("*"):
            if f.is_file() and f.suffix.lower() in (".png", ".jpg", ".jpeg", ".pdf", ".eps"):
                extra[f.relative_to(src_dir).as_posix()] = f.read_bytes()
    for fid in paperlib.figures_used(paper):
        if paper["figures"][fid].get("mode") == "orig" and figure_file(p, fid, "orig").exists():
            extra[f"figures/{fid}.jpg"] = figure_file(p, fid, "orig").read_bytes()

    paper["compile"] = {"engine": None, "ok": False, "errors": [], "template": prof["template"], "fallback": None}
    pdf_path = out / "paper.pdf"
    if pdf_path.exists():
        pdf_path.unlink()
    pages = None
    standard_tex = ""
    if compile_now:
        # A command used in a formula that LaTeX does not define, even with the packages the paper loads (a
        # shorthand a model invented, such as \Fix), is declared as an operator name and said so. Which commands
        # are undefined is asked of TeX itself, on every build, so a wrong declaration made earlier disappears.
        undef = paperlib.undefined_commands(paperlib.build_tex({**paper, "macros": {}}, refs, prof))
        if undef is not None:
            paper["macros"] = {"\\" + n: f"\\operatorname{{{n}}}" for n in undef if "\\" + n not in paperlib.MACROS}
        else:                                      # no LaTeX here to ask: at least never redeclare a known command
            paper["macros"] = {k: v for k, v in (paper.get("macros") or {}).items()
                               if k[1:] not in paperlib.PACKAGE_OF and k[1:] not in paperlib.KNOWN_COMMANDS}
        paper["macros_version"] = 2
        marked = paperlib.build_tex(paper, refs, prof, markers=True)
        res = paperlib.compile_pdf(marked, files=extra)
        if res["pdf"] and res.get("overfull"):        # formulas wider than the page: broken over lines, the standard way
            for _ in range(3):
                if not paperlib.break_overfull(paper, marked, res["overfull"]):
                    break
                marked = paperlib.build_tex(paper, refs, prof, markers=True)
                res = paperlib.compile_pdf(marked, files=extra)
                if not res.get("overfull"):
                    break
        errs = [{**e, "block": paperlib.block_at_line(marked, e["line"])} for e in res["errors"]]
        notes = [{"message": f"{n} is not defined by LaTeX or by any package the paper loads; it is printed as the "
                             f"upright name “{n[1:]}”. If you meant something else, change the passages that use it.",
                  "command": n} for n in sorted(paper.get("macros") or {})]
        notes += [{"message": f"A formula is {o['too_wide']} wider than the page and could not be broken over lines "
                              "by rule; it sticks into the margin. Break it by hand (with split or multline) or ask "
                              "for it to be rewritten.", "block": paperlib.block_at_line(marked, o["line"]), "line": o["line"]}
                  for o in res.get("overfull") or [] if o.get("math")]
        paper["compile"].update(engine=res["engine"], ok=res["ok"], errors=errs, notes=notes)
        pdf, pages = res["pdf"], res["pages"]
        if res["engine"] and not res["ok"] and prof["template"] not in ("amsart", "article"):
            # the journal's class is missing or failed on this computer: the PDF is set in the standard class
            std = {**prof, "template": "article"}
            res2 = paperlib.compile_pdf(paperlib.build_tex(paper, refs, std, markers=True), files=extra)
            if res2["pdf"] and res2["ok"]:
                missing = [m for m in res["missing"] if m.endswith(".cls")]
                paper["compile"].update(ok=True, errors=[], fallback={
                    "template": prof["template"], "missing": missing[0] if missing else "",
                    "errors": [e["message"] for e in res["errors"][:3]]})
                pdf, pages = res2["pdf"], res2["pages"]
                standard_tex = paperlib.build_tex(paper, refs, std)
        if pdf:
            pdf_path.write_bytes(pdf)
        paper["html"] = paperlib.render_html(paper, refs, fig_url_for(p, False))

    tex = paperlib.build_tex(paper, refs, prof)
    (out / "main.tex").write_text(tex, encoding="utf-8")
    bib = "\n\n".join(paperlib.reference_bibtex(x) for x in refs) + "\n"
    (out / "references.bib").write_text(bib, encoding="utf-8")
    (out / "paper.html").write_text(paperlib.standalone_html(paper, refs, fig_url_for(p, True)), encoding="utf-8")
    cls = {"amsart": "amsart", "article": "article", "elsarticle": "elsarticle"}[prof["template"]]
    readme = (f"main.tex uses the LaTeX class \"{cls}\"" + (f", for {prof['journal']}" if prof.get("journal") else "") + ".\n"
              "Upload this folder to Overleaf (New Project > Upload Project) or compile main.tex with pdfLaTeX.\n"
              "The bibliography is embedded in main.tex; references.bib is provided for your reference manager.\n")
    files: dict = {"main.tex": tex, "references.bib": bib, **extra}
    std_path = out / "main_standard_class.tex"
    if std_path.exists():
        std_path.unlink()
    if standard_tex:
        std_path.write_text(standard_tex, encoding="utf-8")
        files["main_standard_class.tex"] = standard_tex
        readme += ("main_standard_class.tex is the same paper in the standard article class, in case the journal's class "
                   "is not installed where you compile.\n")
    files["README.txt"] = readme
    paper["pages"] = pages
    paper["checklist"] = journals.checklist(paper, prof, paper["statements"], pages)
    (out / "paper.zip").write_bytes(paperlib.make_zip(files))
    paper["built"] = time.time()
    p.save("paper", paper)
    p.update_state(lambda st: st.update(paper_title=paper.get("title") or ""))      # shown in the list of papers
    return paper


_draft_cache: dict[str, tuple[str, str]] = {}


def draft_html(p: Project) -> str:
    """The first draft as a page, so that the author can read it while deciding on the proposed changes."""
    body = p.load("body")
    if not body or not body.get("blocks"):
        return ""
    sig = revision.body_sig(p)
    hit = _draft_cache.get(p.id)
    if hit and hit[0] == sig:
        return hit[1]
    library = {x["key"]: x for x in p.load("library", [])}
    intro = (p.load("intro") or {}).get("text", "")
    if body.get("organisation"):
        intro = intro.rstrip() + "\n\n" + body["organisation"]
    paper = {"title": "First draft", "authors": [], "abstract": "", "intro": intro, "figures": body.get("figures") or {},
             "blocks": [dict(b) for b in body["blocks"]], "profile": journals.profile(p.state.get("meta", {}).get("journal"))}
    refs = [library[k] for k in cited_keys([intro] + [b.get("text", "") for b in paper["blocks"]]) if k in library]
    page = paperlib.render_html(paper, refs, fig_url_for(p, False))
    _draft_cache[p.id] = (sig, page)
    return page


# --------------------------------------------------- copy-edit and typography

def _chunks(blocks: list[dict], limit: int) -> list[list[int]]:
    """Runs of consecutive blocks to copy-edit together: a section at a time, cut at block boundaries when a
    section is too long for one request, and never between a statement and the proof that follows it."""
    groups: list[list[int]] = []
    cur: list[int] = []
    size = 0
    for i, b in enumerate(blocks):
        n = len(b.get("text") or b.get("title") or "") + 40
        new_section = b["type"] == "section"
        after_statement = cur and blocks[cur[-1]]["type"] == "env" and b["type"] == "proof"
        if cur and (new_section or (size + n > limit and not after_statement)):
            groups.append(cur)
            cur, size = [], 0
        cur.append(i)
        size += n
    if cur:
        groups.append(cur)
    return groups


def _merge_shape(old: list[dict], new: list[dict]) -> list[dict] | None:
    """The edited part as blocks, provided every heading, statement, proof and figure note is still there, in the
    same order and under the same label. Paragraphs of connecting text may have been joined or split."""
    def solid(bs: list[dict]) -> list[tuple]:
        return [(b["type"], b.get("env", ""), b.get("label", "")) for b in bs if b["type"] != "para"]
    if solid(old) != solid(new):
        return None
    rest = iter([b for b in old if b["type"] != "para"])
    page = old[0].get("page", 0) if old else 0
    out: list[dict] = []
    for b in new:
        if b["type"] == "para":
            out.append({"type": "para", "text": b["text"], "page": page})
            continue
        o = dict(next(rest))
        page = o.get("page", page)
        if o["type"] in ("section", "subsection"):
            o["title"] = b.get("title") or o["title"]
        else:
            o["text"] = b.get("text") or o.get("text", "")
        out.append(o)
    return out


def math_bag(text: str) -> list[str]:
    """Every formula of a passage, inline ones included, each displayed line on its own, in a normal form that
    ignores spacing, delimiters and the punctuation mark at the end."""
    bag: list[str] = []
    for kind, c in split_math(text or ""):
        if kind == "text":
            continue
        for line in (fidelity._lines(c) if kind in ("display", "env") else [c]):
            n = fidelity.normalize(line)
            if n:
                bag.append(n)
    return sorted(bag)


def _formulas_intact(old: str, new: str) -> bool:
    """The edit left the mathematics alone: the same formulas, each the same number of times. Only the
    punctuation that closes a displayed formula may differ."""
    return math_bag(old) == math_bag(new)


def _same_but_syntax(old: str, new: str) -> bool:
    """A repair of LaTeX syntax: braces, dollars and a closing command may change, the content may not."""
    def core(t: str) -> str:
        return re.sub(r"[\s{}$]|\\[\[\]()]", "", t or "")
    a, b = core(old), core(new)
    return bool(b) and difflib.SequenceMatcher(None, a, b, autojunk=False).ratio() >= 0.93


def _points_for(text: str, points: list[dict], labels: set[str]) -> list[dict]:
    """The referee's presentation points that concern this passage; points about the whole paper go everywhere."""
    flat = re.sub(r"\s+", " ", text)
    mine = []
    for x in points:
        where = x.get("where", "")
        named = set(re.findall(r"[A-Za-z]+:[A-Za-z0-9_.\-]+", where))
        quote = re.sub(r"\s+", " ", where).strip("\"'“”` ")
        if not where or where.lower().startswith("whole") or (named & labels) or (len(quote) > 6 and quote in flat):
            mine.append(x)
    return mine[:12]


def _polish_one(run: Run, text: str, points: list[dict], notation: str, choice: str, label: str) -> tuple[str, str]:
    """Copy-edit one passage. Returns (new text or "", what happened)."""
    system = prompts.POLISH.format()
    listing = "\n".join(f"- ({x['type']}) {x['comment']} {x['action']}".strip() for x in points) or "(none for this part)"
    ckey = hashlib.sha256(f"{listing}\n{notation}\n{choice}\n{text}".encode("utf-8")).hexdigest()[:24]
    cache = run.p.load("polish_cache", {}) or {}
    if run.p.state.get("incremental") and ckey in cache:
        return cache[ckey][0], "kept from the last version (unchanged)"
    out = _polish_fresh(run, system, listing, text, notation, choice, label)
    if out[0]:
        cache[ckey] = list(out)
        run.p.save("polish_cache", dict(list(cache.items())[-400:]))
    return out


def _polish_fresh(run: Run, system: str, listing: str, text: str, notation: str, choice: str, label: str) -> tuple[str, str]:
    head = (f"NOTATION CHOICE\n{choice or '(none)'}\n\nCONFIRMED NOTATION\n{notation}\n\n"
            f"REFEREE'S POINTS ON PRESENTATION\n{listing}\n\n")
    why = ""
    for attempt in range(2):
        note = ("NOTE\nYour previous edit of this part was not accepted because it " + why + ". Edit the wording only.\n\n"
                if attempt else "")
        try:
            res = run.ask("writer", system, head + note + "THE PART TO EDIT\n\n" + text,
                          max_out=int(est_tokens(text) * 1.3) + 800, effort="medium",
                          temperature=0.1, label=label + (" (second try)" if attempt else ""))
        except LLMError as e:
            if passing(e):
                raise
            return "", "kept as written (the edit could not be obtained)"
        cand = clean_fragment(res.text)
        if cand.split() == text.split():
            return "", "needed no change"
        if not wording_only(text, cand):
            why = "changed a label, a reference, a citation or an environment, or its length"
        elif not _formulas_intact(text, cand):
            why = "changed, removed or added a formula"
        else:
            return cand, "edited"
    return "", "kept as written (an edit would have changed more than the wording)"


def copy_edit(run: Run, intro: str, blocks: list[dict], state: dict, save) -> tuple[str, list[dict], list[dict]]:
    """One professional copy-edit of the whole paper, part by part, with the referee's presentation points.
    `state` remembers finished parts, so an interruption costs nothing."""
    p = run.p
    d = planned_dossier(p)
    points = [x for x in (p.load("referee") or {}).get("points", []) if x.get("route") == "auto"]
    notation = notation_text(p.load("confirmed", {}), 1500)
    choice = d.get("notation_choice", "")
    limit = state.setdefault("limit", max(3000, min(12000, int(router.budget("writer") * 3 * 0.3))))
    groups = _chunks(blocks, limit)
    done: dict = state.setdefault("chunks", {})
    log: list[dict] = state.setdefault("polish", [])
    total = len(groups) + 1
    blocks = [dict(b) for b in blocks]
    titles: list[str] = []                      # the section each part belongs to, and its number within it
    cur = "Opening"
    for idxs in groups:
        if blocks[idxs[0]]["type"] == "section":
            cur = re.sub(r"\s+", " ", blocks[idxs[0]]["title"])
        titles.append(cur)
    names = [t + (f", part {titles[:i + 1].count(t)}" if titles.count(t) > 1 else "") for i, t in enumerate(titles)]

    if "intro" not in state:
        run.progress(0, total, "copy-editing the introduction")
        mine = [x for x in points if "introduction" in (x["where"] + x["comment"]).lower()] + _points_for(intro, points, set())
        new, what = _polish_one(run, intro, list({x["id"]: x for x in mine}.values()), notation, choice, "Copy-edit introduction")
        state["intro"] = new or intro
        log.append({"part": "Introduction", "result": what})
        save()
    intro = state["intro"]

    out: list[dict] = []
    for gi, idxs in enumerate(groups):
        part = [blocks[i] for i in idxs]
        key = str(gi)
        if key not in done:
            run.progress(gi + 1, total, f"copy-editing: {names[gi]}")
            old = paperlib.blocks_to_latex(part)
            labels = {b["label"] for b in part if b.get("label")} | set(re.findall(r"\\label\{([^{}]+)\}", old))
            new, what = _polish_one(run, old, _points_for(old, points, labels), notation, choice,
                                    f"Copy-edit part {gi + 1} of {len(groups)}")
            merged = None
            if new:
                merged = _merge_shape(part, paperlib.parse_body(new))
                if merged is None:
                    what = "kept as written (an edit would have moved or removed a statement or a proof)"
            done[key] = merged
            log.append({"part": names[gi], "result": what})
            save()
        out += done[key] or part
    for i, b in enumerate(out):
        b["id"] = f"b{i + 1}"
    run.progress(total, total, "copy-edit finished")
    return intro, out, log


def typography(paper: dict) -> dict:
    """The rule-based pass over every passage. Returns how many corrections of each kind were made."""
    totals: dict[str, int] = {}

    def run_on(text: str, close: bool) -> str:
        new, counts = tidy(text)
        if close:
            new, n = close_paragraphs(new)
            counts["stops"] += n
        for k, v in counts.items():
            totals[k] = totals.get(k, 0) + v
        return new

    if paper.get("intro"):
        paper["intro"] = run_on(paper["intro"], True)
    if paper.get("abstract"):
        paper["abstract"] = run_on(paper["abstract"], True)
    for b in paper["blocks"]:
        if b["type"] in ("para", "env", "proof") and b.get("text"):
            b["text"] = run_on(b["text"], True)
    return totals


# ----------------------------------------------------------- abstract, title

def fit_abstract(ask, paper: dict, prof: dict) -> bool:
    """Bring the abstract inside the journal's word range. Returns True if it was rewritten."""
    lo, hi = prof.get("abstract_min_words"), prof.get("abstract_max_words")
    n = journals.words(paper.get("abstract", ""))
    if not paper.get("abstract") or ((not lo or n >= lo) and (not hi or n <= hi)):
        return False
    best = None
    for _ in range(2):
        res = ask("writer", prompts.ABSTRACT_FIT.format(length=journals.length_phrase(prof)),
                  "ABSTRACT\n" + (best or paper["abstract"]), max_out=900, effort="medium", temperature=0.2,
                  label="Fit abstract to the journal's length")
        cand = re.sub(r"\\cite[tp]?\s*(?:\[[^\]]*\])?\s*\{[^{}]*\}", "", clean_fragment(extract_tag(res.text, "abstract") or res.text)).strip()
        if not cand or check_balance(cand):
            continue
        best = cand
        m = journals.words(cand)
        if (not lo or m >= lo) and (not hi or m <= hi):
            break
    if best:
        paper["abstract"], paper["abstract_source"] = best, "generated"
    return bool(best)


def check_citations(ask, parts: list[tuple[str, str]], library: dict) -> list[dict]:
    """For every sentence that cites a paper: does what was read of that paper support it?"""
    sentences = []
    for where, text in parts:
        flat = re.sub(r"\s+", " ", text or "")
        for sent in re.split(r"(?<=[.!?])\s+(?=[A-Z\\])", flat):
            for k in cited_keys([sent]):
                if k in library:
                    sentences.append({"sentence": sent.strip()[:600], "key": k, "where": where})
    checks: list[dict] = []
    if not sentences:
        return checks
    system = prompts.CITE_CHECK.format()
    room = _room("reason", system, 900)
    per = max(4, min(14, room // 1500))
    for start in range(0, len(sentences), per):
        chunk = sentences[start:start + per]
        lines = []
        for i, s in enumerate(chunk, 1):
            x = library[s["key"]]
            nt = x.get("notes") or {}
            ev = "; ".join((nt.get("citable") or []) + (nt.get("results") or []))[:700] or fit(x.get("abstract", ""), 600, "head")
            lines.append(f"{i}. SENTENCE: {s['sentence']}\n   CITED PAPER [{s['key']}]: {x['title']} ({x.get('year')})\n"
                         f"   NOTES ON THAT PAPER: {nt.get('summary', '')} {ev}")
        res = ask("reason", system, "\n\n".join(lines), max_out=900, effort="medium", label="Verify citations")
        for row in parse_rows(extract_tag(res.text, "checks"), min_cols=2):
            m = re.search(r"\d+", row[0])
            if not m or not (1 <= int(m.group(0)) <= len(chunk)):
                continue
            s = chunk[int(m.group(0)) - 1]
            v = row[1].lower()
            verdict = "unsupported" if "unsupported" in v else ("partly" if "part" in v else "supported")
            checks.append({**s, "verdict": verdict, "reason": row[2] if len(row) > 2 else ""})
    return checks


def title_brief(d: dict, abstract: str) -> str:
    """What a title must be true to: the kind of paper, and the main results as the paper presents them."""
    from .writing import KIND_TEXT
    main = [x for x in d.get("results", []) if x["role"] == "main"] or d.get("results", [])[-2:]
    how = {"conjecture": " (stated as a conjecture, not proved)", "credit": " (a known result, credited)",
           "gap": " (its proof is incomplete)", "unproved": " (stated without proof)"}
    return (f"ABSTRACT\n{abstract}\n\n" + (f"KIND OF PAPER\n{KIND_TEXT[d['plan_kind']]}\n\n" if d.get("plan_kind") in KIND_TEXT else "")
            + "MAIN RESULTS\n" + "\n".join(f"- {x['kind']}{how.get(x.get('treatment', ''), '')}"
                                           + (" (conditional on a conjecture)" if x.get("conditional") else "") + f": {x['statement']}" for x in main)
            + f"\n\nTHE PROBLEM ADDRESSED (this is not a title)\n{d.get('problem', '')}")


def stage_assemble(run: Run) -> None:
    p = run.p
    body = p.load("body", {})
    d = planned_dossier(p)
    meta = run.meta
    prof = journals.profile(meta.get("journal"))
    library = {x["key"]: x for x in p.load("library", [])}
    front = p.load("front") or {}
    sig = hashlib.sha1((revision.body_sig(p) + json.dumps(p.load("decisions") or {}, sort_keys=True)).encode("utf-8")).hexdigest()[:16]
    state = p.load("final_partial") or {}
    if state.get("sig") != sig:
        state, front = {"sig": sig}, {}

    def save() -> None:
        p.save("final_partial", state)

    # 1. the author's decisions
    run.progress(0, 6, "carrying out your decisions")
    notes: list[str] = list((p.load("intro") or {}).get("notes", []))
    if "blocks" not in state:
        blocks, decided, waived, approved, report = revision.apply_decisions(
            run, body.get("blocks", []), (p.load("intro") or {}).get("text", ""))
        state.update(blocks=blocks, intro_decided=decided, waived=waived, approved=approved, report=report)
        save()
        done = len(report["simplified"]) + len(report.get("completed", [])) + len(report["corrected"]) + len(report["instructed"]) + len(report["remarks"])
        if done or report["unapplied"]:
            run.log(f"{done} decided change(s) made." + (f" {len(report['unapplied'])} could not be made automatically; "
                    "they are listed in the Revision tab." if report["unapplied"] else ""),
                    "warn" if report["unapplied"] else "info")
    report = state["report"]

    # 2. one copy-edit of everything, with the referee's points on presentation
    intro0 = fix_keys(state["intro_decided"], library, notes)
    if body.get("organisation"):
        intro0 = intro0.rstrip() + "\n\n" + body["organisation"]
    intro, blocks, polish_log = copy_edit(run, intro0, state["blocks"], state, save)
    edited = sum(1 for x in polish_log if x["result"] == "edited")
    run.log(f"Copy-edit: {edited} of {len(polish_log)} part(s) edited; the others needed no change or were kept as written.")

    # 3. citations: only keys that exist in the verified library survive
    run.progress(2, 6, "checking citations")
    fresh: list[str] = []
    for b in blocks:
        if b.get("text"):
            b["text"] = fix_keys(b["text"], library, fresh)
    for n in fresh:
        run.log(n, "warn")
    notes += fresh
    checks: list[dict] = front.get("cite_checks") or []
    if "cite_checks" not in front:
        checks = check_citations(run.ask, [("Introduction", intro)] + [("body", b.get("text", "") + " " + (b.get("title") or ""))
                                                                     for b in blocks], library)
        front["cite_checks"] = checks
        p.save("front", front)
    bad = [c for c in checks if c["verdict"] != "supported"]
    if bad:
        run.log(f"{len(bad)} citation(s) may not be fully supported by the cited paper. See the Citations tab.", "warn")

    body_tex = paperlib.blocks_to_latex(blocks)
    main = [x for x in d.get("results", []) if x["role"] == "main"] or d.get("results", [])[-2:]

    # 4. the abstract, from the finished text, at the length the journal asks for
    run.progress(3, 6, "writing the abstract")
    if not front.get("abstract"):
        system = prompts.ABSTRACT.format(field=run.field, length=journals.length_phrase(prof).capitalize(),
                                         keywords=journals.keywords_phrase(prof))
        room = _room("writer", system, 900)
        user = (f"DOSSIER\n{dossier_text(d, max(1200, int(room * 0.35)))}\n\nINTRODUCTION\n{fit(intro, max(800, int(room * 0.2)), 'head')}\n\n"
                f"BODY\n{fit(body_tex, max(1000, int(room * 0.4)), 'middle')}")
        res = run.ask("writer", system, user, max_out=900, effort="medium", label="Write abstract")
        abstract = re.sub(r"\\cite[tp]?\s*(?:\[[^\]]*\])?\s*\{[^{}]*\}", "", clean_fragment(extract_tag(res.text, "abstract"))).strip()
        if len(abstract) < 80:
            raise LLMError("The abstract came back empty.", kind="transient", retry_at=time.time() + 60)
        front["abstract"] = abstract
        front["keywords"] = parse_list(extract_tag(res.text, "keywords"))[:12]
        front["msc"] = [m for m in (re.sub(r"[^0-9A-Za-z\-]", "", x) for x in parse_list(extract_tag(res.text, "msc")))
                        if re.match(r"^\d{2}[A-Z\-]", m)][:4]
        holder = {"abstract": abstract}
        if fit_abstract(run.ask, holder, prof):
            front["abstract"] = holder["abstract"]
        p.save("front", front)

    # 5. the title, last of all: it names what the finished paper is about
    run.progress(4, 6, "choosing the title")
    if not front.get("title_candidates"):
        system = prompts.TITLE.format()
        user = f"FIELD\n{run.field}\n\n" + title_brief(d, front["abstract"])
        cands: list[str] = []
        for attempt in range(2):
            res = run.ask("writer", system, user, max_out=500, effort="medium", temperature=0.5,
                          label="Propose titles" + (" (retry)" if attempt else ""))
            raw = extract_tag(res.text, "titles") or res.text
            cands = [re.sub(r"^\s*(?:\d+[.)]|[-*•])\s*", "", t).strip(' "“”') for t in raw.splitlines() if t.strip()]
            cands = [clean_fragment(t).rstrip(".") for t in cands]
            cands = [t for t in dict.fromkeys(cands) if good_title(t)]
            if cands:
                break
        front["title_candidates"] = cands[:5]
        p.save("front", front)
    if meta.get("title", "").strip():
        title, source = meta["title"].strip(), "author"
    elif front.get("title_candidates"):
        title, source = front["title_candidates"][0], "suggested"         # until the author chooses at the next step
    else:
        title, source = "Untitled", "suggested"
        run.log("No acceptable title was proposed; write your own at the next step.", "warn")

    paper = {
        "title": title, "title_source": source, "title_candidates": front.get("title_candidates", []),
        "authors": meta.get("authors") or [], "abstract": front["abstract"], "abstract_source": "generated",
        "intro": intro, "intro_source": "generated", "keywords": front.get("keywords", []), "msc": front.get("msc", []),
        "blocks": blocks, "figures": body.get("figures") or {}, "cite_checks": checks, "cite_notes": notes,
        "concerns": d.get("concerns", []), "plan": (p.load("plan") or {}).get("sections", []),
        "waived": "\n".join(x for x in (state.get("waived", ""), left_out_text(p)) if x), "approved_text": state.get("approved", ""),
    }

    # 6. typography by rule, then the files; LaTeX that will not compile is repaired passage by passage
    counts = typography(paper)
    ref = p.load("referee") or {}
    paper["revision"] = {
        **report, "polish": polish_log, "typography": counts,
        "referee": {"summary": ref.get("summary", ""), "recommendation": ref.get("recommendation", ""),
                    "handled": [x for x in ref.get("points", []) if x.get("route") == "auto"]},
        "proofs": {"checked": sum(1 for r in ((p.load("verify") or {}).get("results") or {}).values()
                                  if r["verdict"] in ("correct", "problems")),
                   "clean": sum(1 for r in ((p.load("verify") or {}).get("results") or {}).values() if r["verdict"] == "correct")},
    }
    p.save("revision", paper["revision"])
    run.log("Typography: " + (", ".join(f"{v} {k}" for k, v in counts.items() if v) or "nothing to correct") + ".")
    run.progress(5, 6, "building the files")
    for rnd in range(2):
        paper = build_outputs(p, paper)
        targets: dict[str, str] = {}
        for e in paper["compile"]["errors"]:
            if e.get("block") and e["block"] != "refs":
                targets.setdefault(e["block"], e["message"])
        if not paper["compile"]["ok"]:
            for item in paper["lint"]:
                if item["block"] and "marker" not in item["message"]:
                    targets.setdefault(item["block"], item["message"])
        if not targets or rnd == 1:
            break
        run.log(f"Repairing LaTeX syntax in {len(targets)} place(s).")
        system = prompts.LATEX_FIX.format()
        for bid, msg in list(targets.items())[:8]:
            if bid in ("intro", "abstract"):
                src = paper[bid]
            else:
                blk = next((b for b in paper["blocks"] if b.get("id") == bid), None)
                if not blk or not blk.get("text"):
                    continue
                src = blk["text"]
            try:
                res = run.ask("reason", system, f"ERROR: {msg}\n\nFRAGMENT:\n{src}", max_out=int(est_tokens(src) * 1.2) + 400, paper=True,
                              effort="low", label=f"Fix LaTeX in {bid}", temperature=0.0)
            except LLMError as e:
                if passing(e):
                    raise
                continue
            fixed = clean_fragment(res.text)
            if not fixed or len(check_balance(fixed)) > len(check_balance(src)) or not _same_but_syntax(src, fixed):
                continue
            if bid in ("intro", "abstract"):
                paper[bid] = fixed
            else:
                blk["text"] = fixed
    run.progress(6, 6, "final version ready")
    c = paper["compile"]
    if c["engine"] and c["ok"] and c.get("fallback"):
        run.log(f"The journal's LaTeX class ({c['fallback']['template']}) could not be used on this computer, so the PDF is set "
                "in the standard class. The package contains both versions.", "warn")
    elif c["engine"] and c["ok"]:
        run.log(f"Compiled to PDF with {c['engine']}.")
    elif c["engine"]:
        run.log("The LaTeX still has compile errors; they are listed in the paper view.", "warn")
    else:
        run.log("No LaTeX engine is installed on this computer, so no PDF was produced. The Overleaf package is ready.")
    a = paper["audit"]
    run.log(f"Formulas: {a['preserved']} of {a['total']} identical to your notes; {len(a.get('agreed', []))} changed with your "
            f"approval; {len(a['altered']) + len(a['missing'])} to look at.",
            "warn" if a["altered"] or a["missing"] else "info")
    open_items = [x for x in paper.get("checklist", []) if not x["ok"]]
    if open_items:
        run.log("Journal requirements still open: " + "; ".join(x["label"] for x in open_items) + ".", "warn")
    run.log(f"{len(paper.get('title_candidates', []))} titles suggested; you choose one at the next step.")
    run.log(f"References: {len(paper['refs'])} cited; {len(paper['uncited'])} read but not cited (left out).")


# ------------------------------------------------------ after the final version

def _hooks(p: Project) -> Run:
    h = Run(p)
    h.stage = "assemble"
    return h


def revise_block(p: Project, target: str, instruction: str) -> dict:
    """Author-requested rewrite of one passage (abstract, introduction, or a passage of the body)."""
    paper = p.load("paper")
    if not paper:
        raise ValueError("The paper has not been assembled yet.")
    blk = None
    if target in ("abstract", "intro"):
        src = paper.get(target, "")
    else:
        blk = next((b for b in paper["blocks"] if b.get("id") == target), None)
        if not blk:
            raise ValueError("Unknown passage.")
        src = blk.get("text") or blk.get("title", "")
    user = (f"AUTHOR'S INSTRUCTION\n{instruction}\n\nCONFIRMED NOTATION\n{notation_text(p.load('confirmed', {}), 1200)}\n\n"
            f"PASSAGE\n{src}")
    res = router.chat("writer", prompts.REVISE.format(), user, max_out=int(est_tokens(src) * 1.5) + 500,
                      label=f"Revise {target}", hooks=_hooks(p), temperature=0.2)
    new = clean_fragment(res.text)
    if target in ("abstract", "intro"):
        paper[target] = new
    elif blk.get("text") is not None and blk["type"] not in ("section", "subsection"):
        blk["text"] = new
    else:
        blk["title"] = new
    return build_outputs(p, paper)


def set_journal(p: Project, journal: dict | None, statements: dict | None = None,
                cite_software: bool | None = None) -> dict | None:
    """Choose, change or clear the target journal. If a paper exists it is refitted and rebuilt at once."""
    clean = journals.clean_journal(journal)

    def f(st):
        st["meta"]["journal"] = clean
        if cite_software is not None:
            st["meta"]["cite_software"] = bool(cite_software)
        if statements is not None:
            st["meta"]["statements"] = {k: re.sub(r"\s+", " ", str(statements.get(k) or "")).strip()[:1500]
                                        for k, _ in paperlib.STATEMENTS}
    p.update_state(f)
    paper = p.load("paper")
    if not paper:
        return None
    prof = journals.profile(clean)
    if paper.get("abstract_source") != "author":            # an abstract the author wrote is never rewritten
        try:
            fit_abstract(lambda role, system, user, **kw: router.chat(role, system, user, hooks=_hooks(p), **kw), paper, prof)
        except LLMError:
            pass                                # the checklist will say that the abstract is outside the range
    return build_outputs(p, paper)


def read_guide(p: Project, source: str) -> dict:
    """Read the journal's guide for authors (a web address or pasted text) into requirement values for the
    author to confirm. Nothing is applied here."""
    def ask(system: str, user: str) -> str:
        return router.chat("fast", system, fit(user, _room("fast", system, 900), "head"), json_mode=True, max_out=900,
                           effort="low", label="Read the journal's guide for authors", hooks=_hooks(p)).text
    return journals.read_guide(source, ask)


# ------------------------------------------------ the last step: title, introduction, citations

def related_papers(p: Project, paper: dict | None = None) -> list[dict]:
    """The papers closest to the notes, for the author to choose what the introduction cites: those found by the
    searches, most relevant first, with what is known about each and whether the paper cites it now."""
    paper = paper or p.load("paper") or {}
    cited = set(cited_keys([paper.get("intro", "")] + [b.get("text", "") + " " + (b.get("title") or "") for b in paper.get("blocks", [])]))
    out = []
    for x in p.load("library", []):
        if x.get("state") == "excluded":
            continue
        score = float(x.get("score") or 0)
        if score < 5 and x["key"] not in cited and not x.get("pinned"):
            continue
        nt = x.get("notes") or {}
        out.append({"key": x["key"], "title": x.get("title", ""), "year": x.get("year"), "venue": x.get("venue", ""),
                    "authors": ", ".join(a.get("family") or a.get("given", "") for a in (x.get("authors") or [])[:4])
                               + (" et al." if len(x.get("authors") or []) > 4 else ""),
                    "doi": x.get("doi", ""), "arxiv": x.get("arxiv", ""), "url": x.get("url", ""),
                    "score": score, "why": x.get("why", ""), "read": bool(x.get("read")),
                    "summary": (nt.get("summary") or "")[:500], "cited": x["key"] in cited,
                    "in_intro": x["key"] in set(cited_keys([paper.get("intro", "")]))})
    out.sort(key=lambda r: (not r["cited"], -r["score"], -(r["year"] or 0)))
    return out[:25]


def open_items(p: Project, paper: dict | None = None) -> list[dict]:
    """What still stands between this paper and a submission. 'error' items are serious: the paper says something
    that the checks found to be wrong or unproved; 'note' items deserve a look."""
    paper = paper or p.load("paper") or {}
    items = []
    dec = (p.load("decisions") or {}).get("issues") or {}
    for c in revision.decision_items(p)["issues"]:
        if (dec.get(c["id"]) or {}).get("choice") == "keep" and c.get("severity") == "error":
            items.append({"level": "error", "text": f"{c['name']}: you kept the proof as it is, although the proof check "
                                                    f"and a second opinion found an error in it."})
    d = planned_dossier(p)
    unapplied = {x.get("id") for x in (paper.get("revision") or {}).get("unapplied", [])}
    changed = {c["label"] for c in revision.decision_items(p)["issues"]
               if (dec.get(c["id"]) or {}).get("choice") in ("fix", "instruct") and c["id"] not in unapplied}
    cdec = (p.load("decisions") or {}).get("complete") or {}
    for c in revision.decision_items(p)["complete"]:
        how = (cdec.get(c["id"]) or {}).get("choice")
        if how in ("accept", "edit", "instruct") and c["id"] not in unapplied:
            changed.add(c["label"])
        elif how == "keep":
            items.append({"level": "note", "text": f"{c['name']}: its proof is a sketch, and you kept the sketch rather than the completed proof."})
    for x in d.get("results", []):
        if x.get("treatment") == "gap" and f"res:{x['id']}" not in changed:
            items.append({"level": "error", "text": f"Result {x['id']}: its proof in your notes is incomplete, and it is "
                                                    "presented as proved."})
    for x in d.get("results", []):
        if x.get("treatment") == "unproved":
            items.append({"level": "error", "text": f"Result {x['id']}: your notes give no proof of it, and it is presented as a result."})
        if x.get("conditional"):
            items.append({"level": "note", "text": f"Result {x['id']} is proved only assuming the conjecture(s) "
                                                   f"{', '.join(x['conditional'])}; the paper must say so."})
    conj = [x["id"] for x in d.get("results", []) if x.get("treatment") == "conjecture"]
    if conj:
        items.append({"level": "note", "text": f"{len(conj)} statement(s) appear as conjectures, without proof."})
    a = p.load("assessment") or {}
    if a.get("main") and a["main"] != "established" and d.get("plan_kind") == "article":
        items.append({"level": "error", "text": "The assessment found that the notes do not fully establish the main "
                                                "result, but the paper is written as a research article."})
    bad = [c for c in paper.get("cite_checks", []) if c.get("verdict") == "unsupported"]
    if bad:
        items.append({"level": "note", "text": f"{len(bad)} citation(s) may not be supported by the cited paper "
                                               "(see the Citations tab)."})
    au = paper.get("audit") or {}
    if au.get("altered") or au.get("missing"):
        items.append({"level": "error", "text": f"{len(au.get('altered', [])) + len(au.get('missing', []))} formula(s) of "
                                                "your notes are altered or missing (see the Fidelity tab)."})
    if (paper.get("compile") or {}).get("engine") and not (paper.get("compile") or {}).get("ok"):
        items.append({"level": "error", "text": "The LaTeX file does not compile yet."})
    for x in paper.get("checklist", []):
        if not x.get("ok"):
            items.append({"level": "note", "text": f"Journal requirement: {x['label']}."})
    return items


def finish_info(p: Project) -> dict | None:
    paper = p.load("paper")
    if not paper:
        return None
    return {"titles": paper.get("title_candidates", []), "title": paper.get("title", ""),
            "title_source": paper.get("title_source", ""), "related": related_papers(p, paper),
            "open": open_items(p, paper), "finished": p.load("finished")}


def more_titles(p: Project) -> dict:
    """Five further title suggestions, different from those already offered."""
    paper = p.load("paper")
    if not paper:
        raise ValueError("The paper has not been assembled yet.")
    d = planned_dossier(p)
    have = paper.get("title_candidates", [])
    user = (title_brief(d, paper.get("abstract", "")) + "\n\nALREADY SUGGESTED (propose five different ones)\n"
            + "\n".join(f"- {t}" for t in have))
    res = router.chat("writer", prompts.TITLE.format(), user, max_out=500, temperature=0.7, effort="medium",
                      label="Propose more titles", hooks=_hooks(p))
    raw = extract_tag(res.text, "titles") or res.text
    cands = [clean_fragment(re.sub(r"^\s*(?:\d+[.)]|[-*•])\s*", "", t).strip(' "“”')).rstrip(".") for t in raw.splitlines() if t.strip()]
    new = [t for t in dict.fromkeys(cands) if good_title(t) and t not in have]
    if not new:
        raise ValueError("No new acceptable title came back. Write your own, or try again.")
    paper["title_candidates"] = have + new[:5]
    p.save("paper", paper)
    return paper


def cite_intro(p: Project, keys: list[str], instruction: str = "") -> dict:
    """Rewrite the introduction so that it cites exactly the papers the author ticked. Facts about a paper come only
    from what was read of it; the paper's own results and every formula stay as they are."""
    paper = p.load("paper")
    if not paper:
        raise ValueError("The paper has not been assembled yet.")
    library = {x["key"]: x for x in p.load("library", [])}
    keys = [k for k in dict.fromkeys(keys) if k in library]
    lines = []
    for k in keys:
        x = library[k]
        nt = x.get("notes") or {}
        facts = "; ".join((nt.get("citable") or []) + (nt.get("results") or []))
        lines.append(f"[{k}] {x.get('title', '')} ({x.get('year') or 'n.d.'}). "
                     + (f"Notes: {nt.get('summary', '')} {facts}" if nt else f"Abstract: {fit(x.get('abstract', ''), 900, 'head') or '(not available)'}"))
    old = paper.get("intro", "")
    user = (f"INTRODUCTION\n{old}\n\nPAPERS TO CITE\n" + ("\n".join(lines) or "(none: remove every citation)")
            + (f"\n\nTHE AUTHOR'S INSTRUCTION\n{instruction}" if instruction.strip() else ""))
    res = router.chat("writer", prompts.INTRO_CITE.format(), user, max_out=int(est_tokens(old) * 1.6) + 800, temperature=0.2,
                      effort="high", label="Rewrite the introduction for the chosen citations", hooks=_hooks(p))
    notes: list[str] = []
    new = fix_keys(clean_fragment(res.text), library, notes)                      # near-miss keys of real papers
    new = fix_keys(new, {k: library[k] for k in keys}, notes, fuzzy=False)        # then exactly the papers chosen
    new = re.sub(r"\\section\*?\{[^{}]*\}\s*", "", new).strip()
    if len(new) < 0.4 * len(old):
        raise ValueError("The rewritten introduction came back much shorter than before, so it was not used. Try again.")
    old_bag = math_bag(old)
    added = [f for f in math_bag(new) if f not in old_bag]
    if added:
        raise ValueError("The rewritten introduction changed or added formulas, so it was not used. Try again, or edit it yourself.")
    paper["intro"], paper["intro_source"] = new, "rewritten for your citations"
    ask = lambda role, system, user, **kw: router.chat(role, system, user, hooks=_hooks(p), **kw)
    paper["cite_checks"] = [c for c in paper.get("cite_checks", []) if c.get("where") != "Introduction"] \
        + check_citations(ask, [("Introduction", new)], library)
    paper["cite_notes"] = [n for n in paper.get("cite_notes", []) if "corrected to" not in n] + [n for n in notes if "corrected to" in n]
    return build_outputs(p, paper)


def finish(p: Project, data: dict) -> dict:
    """The author's last word: the title, the introduction as approved. The files are built once more."""
    paper = p.load("paper")
    if not paper:
        raise ValueError("The paper has not been assembled yet.")
    title = re.sub(r"\s+", " ", str(data.get("title") or "")).strip()
    if not title:
        raise ValueError("Choose a title, or write your own.")
    if check_balance(title):
        raise ValueError("The title has an unbalanced $ or brace.")
    paper["title"] = title
    own = title not in paper.get("title_candidates", [])
    paper["title_source"] = "author" if own else "chosen by you"
    # only a title the author wrote outlives a new final version; a chosen suggestion is chosen again from new ones
    p.update_state(lambda st: st["meta"].update(title=title if own else ""))
    if isinstance(data.get("intro"), str) and data["intro"].strip() and data["intro"].strip() != paper.get("intro", "").strip():
        paper["intro"], paper["intro_source"] = data["intro"].strip(), "author"
    paper = build_outputs(p, paper)
    p.save("finished", {"at": time.time(), "title": title})
    p.set_stage("finish", status="done", finished=time.time())
    return paper


