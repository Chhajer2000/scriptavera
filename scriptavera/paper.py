# ------------------------------------------------------------- parsing

def open_environments(latex: str) -> list[str]:
    """Block environments still open at the end of a fragment."""
    stack: list[str] = []
    for m in re.finditer(r"\\(begin|end)\{([a-zA-Z*]+)\}", re.sub(r"(?<!\\)%.*", "", latex or "")):
        name = m.group(2)
        if name not in _BLOCK_ENVS:
            continue
        if m.group(1) == "begin":
            stack.append(name)
        elif stack and stack[-1] == name:
            stack.pop()
    return stack


def close_open(latex: str) -> str:
    for env in reversed(open_environments(latex)):
        latex += f"\n\\end{{{env}}}"
    return latex


def parse_body(latex: str) -> list[dict]:
    """Split a LaTeX body fragment into blocks: sections, statements, proofs, paragraphs."""
    src = close_open(latex or "")
    envs = "|".join(sorted(_BLOCK_ENVS))
    # structural commands always start their own line, which keeps the scan below simple
    src = re.sub(r"[ \t]*(\\begin\{(?:" + envs + r")\*?\})", r"\n\1", src)
    src = re.sub(r"(\\end\{(?:" + envs + r")\*?\})[ \t]*", r"\1\n", src)
    src = re.sub(r"[ \t]*(\\(?:sub){0,2}section\*?\s*\{)", r"\n\1", src)
    blocks: list[dict] = []
    page = [0]
    buf: list[str] = []

    def flush() -> None:
        text = "\n".join(buf).strip()
        buf.clear()
        for para in _split_paragraphs(text):
            blocks.append({"type": "para", "text": para, "page": page[0]})

    lines = src.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        pm = re.match(r"^%+\s*page\s+(\d+)\s*$", s, re.I)
        if pm:
            flush()
            page[0] = int(pm.group(1))
            i += 1
            continue
        sm = re.match(r"^\\((?:sub){0,2}section)\*?\s*\{", s)
        if sm:
            flush()
            g = find_group(s, s.index("{"))
            title = g[0] if g else s[s.index("{") + 1:].rstrip("}")
            rest = s[g[1]:].strip() if g else ""
            lab = re.match(r"\\label\{([^{}]+)\}", rest)
            if lab:
                rest = rest[lab.end():].strip()
            blocks.append({"type": "section" if sm.group(1) == "section" else "subsection",
                           "title": title.strip(), "label": lab.group(1) if lab else "", "page": page[0]})
            if rest:
                buf.append(rest)
            i += 1
            continue
        bm = re.match(r"^\\begin\{([a-zA-Z]+)\*?\}", s)
        if bm and bm.group(1) in _BLOCK_ENVS:
            flush()
            env = bm.group(1)
            depth, body_lines, start_page = 0, [], page[0]
            j = i
            while j < len(lines):
                cur = lines[j]
                pm2 = re.match(r"^%+\s*page\s+(\d+)\s*$", cur.strip(), re.I)
                j += 1
                if pm2:
                    page[0] = int(pm2.group(1))
                    continue
                depth += len(re.findall(r"\\begin\{" + env + r"\*?\}", cur))
                depth -= len(re.findall(r"\\end\{" + env + r"\*?\}", cur))
                body_lines.append(cur)
                if depth <= 0:
                    break
            inner = "\n".join(body_lines).strip()
            inner = re.sub(r"^\\begin\{" + env + r"\*?\}", "", inner, count=1)
            inner = re.sub(r"\\end\{" + env + r"\*?\}$", "", inner, count=1)
            title = ""
            if re.match(r"^\s*\[", inner):
                start = inner.index("[")
                depth_b, k = 0, start
                for k in range(start, len(inner)):
                    if inner[k] == "[":
                        depth_b += 1
                    elif inner[k] == "]":
                        depth_b -= 1
                        if depth_b == 0:
                            break
                title = inner[start + 1:k].strip()
                inner = inner[k + 1:]
            label = ""
            lm = re.match(r"^\s*\\label\{([^{}]+)\}", inner)
            if lm:
                label = lm.group(1)
                inner = inner[lm.end():]
            typ = "proof" if env == "proof" else ("figure" if env == "figurenote" else "env")
            blocks.append({"type": typ, "env": env, "title": title, "label": label,
                           "text": inner.strip(), "page": start_page})
            i = j
            continue
        em = re.match(r"^\\end\{([a-zA-Z]+)\*?\}\s*$", s)
        if em and em.group(1) in _BLOCK_ENVS:
            i += 1                               # a stray closing tag
            continue
        buf.append(line)
        i += 1
    flush()
    for n, b in enumerate(blocks):
        b["id"] = f"b{n + 1}"
        if b.get("text"):
            b["text"] = escape_percent(b["text"])       # page markers are gone; any % left is a literal percent
    return blocks


def _split_paragraphs(text: str) -> list[str]:
    """Split on blank lines, but never inside a displayed formula or a list."""
    paras, cur, depth, bracket = [], [], 0, 0
    for line in text.split("\n"):
        depth += len(re.findall(r"\\begin\{", line)) - len(re.findall(r"\\end\{", line))
        bracket += line.count("\\[") - line.count("\\]")
        if not line.strip() and depth <= 0 and bracket <= 0:
            if cur:
                paras.append("\n".join(cur).strip())
                cur = []
            depth = bracket = 0
        else:
            cur.append(line)
    if cur:
        paras.append("\n".join(cur).strip())
    return [p for p in paras if p]


_FIG_RE = re.compile(r"\\insertfigure\s*\{\s*([A-Za-z0-9_]+)\s*\}")
TIKZ_LIBS = "arrows.meta,positioning,calc,decorations.pathreplacing,shapes.geometric,fit"


def figure_latex(fid: str, figs: dict) -> str:
    f = (figs or {}).get(fid)
    if not f or f.get("mode") not in ("tikz", "orig"):
        return ""
    inner = f["tikz"].strip() if f["mode"] == "tikz" else f"\\includegraphics[width=0.82\\textwidth]{{figures/{fid}.jpg}}"
    cap = clean_fragment(f.get("caption") or "")
    return ("\n\\begin{figure}[ht]\n\\centering\n" + inner + "\n"
            + (f"\\caption{{{cap}}}" if cap else "") + f"\\label{{fig:{fid}}}\n\\end{{figure}}\n")


def figures_used(paper: dict) -> list[str]:
    """Figure ids in the order they appear in the paper (only those the author kept)."""
    figs = paper.get("figures") or {}
    seen: list[str] = []
    for text in [paper.get("intro") or ""] + [b.get("text") or "" for b in paper.get("blocks", [])]:
        for m in _FIG_RE.finditer(text):
            fid = m.group(1)
            if fid in figs and figs[fid].get("mode") in ("tikz", "orig") and fid not in seen:
                seen.append(fid)
    return seen


def blocks_to_latex(blocks: list[dict], markers: bool = False, figs: dict | None = None) -> str:
    if figs is not None:
        blocks = [dict(b, text=_FIG_RE.sub(lambda m: figure_latex(m.group(1), figs), b["text"])) if b.get("text") else b
                  for b in blocks]
    out = []
    for b in blocks:
        if markers:
            out.append(f"%@block {b.get('id', '')}")
        t = b["type"]
        if t in ("section", "subsection"):
            lab = f"\\label{{{b['label']}}}" if b.get("label") else ""
            out.append(f"\\{t}{{{b['title']}}}{lab}\n")
        elif t in ("env", "proof", "figure"):
            env = b.get("env") or ("proof" if t == "proof" else "remark")
            opt = f"[{b['title']}]" if b.get("title") else ""
            lab = f"\\label{{{b['label']}}}" if b.get("label") else ""
            out.append(f"\\begin{{{env}}}{opt}{lab}\n{b['text'].strip()}\n\\end{{{env}}}\n")
        else:
            out.append(b["text"].strip() + "\n")
    return "\n".join(out)


# ----------------------------------------------------- numbering and refs

def number_blocks(paper: dict) -> dict:
    """Assign section and theorem numbers exactly as LaTeX will (shared counter per section)."""
    labels: dict[str, str] = {}
    sec = 0
    sub = 0
    thm = 0
    eq = [0]
    if paper.get("intro"):
        sec = 1
    for n, fid in enumerate(figures_used(paper), 1):
        labels[f"fig:{fid}"] = str(n)
    for b in paper.get("blocks", []):
        if b["type"] == "section":
            sec += 1
            sub = 0
            thm = 0
            b["num"] = str(sec)
        elif b["type"] == "subsection":
            sub += 1
            b["num"] = f"{sec}.{sub}"
        elif b["type"] == "env":
            thm += 1
            b["num"] = f"{sec}.{thm}" if sec else str(thm)
        if b.get("label") and b.get("num"):
            labels[b["label"]] = b["num"]
        for m in re.finditer(r"\\begin\{equation\}(.*?)\\end\{equation\}", b.get("text", ""), flags=re.S):
            eq[0] += 1
            lm = re.search(r"\\label\{([^{}]+)\}", m.group(1))
            if lm:
                labels[lm.group(1)] = str(eq[0])
        for lm in re.finditer(r"\\label\{([^{}]+)\}", b.get("text", "")):
            labels.setdefault(lm.group(1), b.get("num") or "?")
    return labels


