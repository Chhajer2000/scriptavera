def build_tex(paper: dict, refs: list[dict], profile: dict | str | None = None, markers: bool = False) -> str:
    """The complete LaTeX file, generated by code. `profile` holds the journal's requirements (see journals.py);
    its "template" picks the class: amsart, article or elsarticle."""
    if isinstance(profile, str):
        profile = {"template": profile}
    prof = {**(paper.get("profile") or {}), **(profile or {})}
    tpl = prof.get("template") if prof.get("template") in ("amsart", "article", "elsarticle") else "amsart"
    anonymous = bool(prof.get("anonymous"))
    title = escape_specials(clean_fragment(paper.get("title") or "Untitled"))
    authors = [] if anonymous else [a for a in paper.get("authors") or [] if a.get("name", "").strip()]
    esc = lambda x: latex_escape(x, keep_math=False)                                     # noqa: E731
    L: list[str] = []
    if tpl == "amsart":
        L.append("\\documentclass[11pt,reqno]{amsart}")
    elif tpl == "elsarticle":
        L.append("\\documentclass[preprint,11pt]{elsarticle}")
    else:
        L.append("\\documentclass[11pt]{article}")
    L += [
        "\\usepackage[T1]{fontenc}", "\\usepackage[utf8]{inputenc}",
        "\\IfFileExists{lmodern.sty}{\\usepackage{lmodern}}{}",
        "\\usepackage{amsmath,amssymb,amsthm,mathtools}", "\\usepackage{enumitem}", "\\usepackage{xcolor}",
        "\\PassOptionsToPackage{hyphens}{url}",
        "\\usepackage[colorlinks=true,linkcolor=blue!55!black,citecolor=blue!55!black,urlcolor=blue!55!black]{hyperref}",
    ]
    figs = paper.get("figures") or {}
    used_figs = figures_used(paper)
    if used_figs:
        L.append("\\usepackage{graphicx}")
        if any(figs[f]["mode"] == "tikz" for f in used_figs):
            L += ["\\usepackage{tikz}", f"\\usetikzlibrary{{{TIKZ_LIBS}}}"]
    if tpl == "article":
        L.append("\\usepackage[margin=1in]{geometry}")
    if prof.get("double_spacing"):
        L += ["\\usepackage{setspace}", "\\doublespacing"]
    if prof.get("line_numbers"):
        L.append("\\usepackage{lineno}")
    L += ["", "\\theoremstyle{plain}", "\\newtheorem{theorem}{Theorem}[section]"]
    L += [f"\\newtheorem{{{e}}}[theorem]{{{THEOREM_ENVS[e]}}}" for e in _PLAIN if e != "theorem"]
    L.append("\\theoremstyle{definition}")
    L += [f"\\newtheorem{{{e}}}[theorem]{{{THEOREM_ENVS[e]}}}" for e in _DEFN]
    L.append("\\theoremstyle{remark}")
    L += [f"\\newtheorem{{{e}}}[theorem]{{{THEOREM_ENVS[e]}}}" for e in _REMARK]
    body_text = (paper.get("intro") or "") + "\n" + "\n".join((b.get("text") or "") for b in paper.get("blocks", []))
    used = set(re.findall(r"\\begin\{([A-Za-z]+)\*?\}", body_text)) | {b.get("env") for b in paper.get("blocks", []) if b.get("env")}
    extra = sorted(e for e in used if e and e not in THEOREM_ENVS and e not in _KNOWN_ENVS and e.isalpha())
    if extra:                                    # an environment the writer used that LaTeX would not know
        L.append("\\theoremstyle{definition}")
        L += [f"\\newtheorem{{{e}}}[theorem]{{{e.capitalize()}}}" for e in extra]
    L += [f"\\providecommand{{{k}}}{{{v}}}" for k, v in {**MACROS, **(paper.get("macros") or {})}.items()]
    L += ["\\newenvironment{figurenote}{\\par\\smallskip\\noindent\\textit{Figure in the notes.}\\ }{\\par\\smallskip}", ""]

    kw_list = [latex_escape(k) for k in paper.get("keywords") or []]
    msc = [m for m in paper.get("msc") or [] if m]
    abstract = escape_specials(clean_fragment(paper.get("abstract") or ""), underscore=False)
    open_doc = ["", "\\begin{document}"] + (["\\linenumbers"] if prof.get("line_numbers") else []) + [""]

    if tpl == "amsart":
        L.append(f"\\title{{{title}}}")
        for a in authors:
            L.append(f"\\author{{{esc(a['name'])}}}")
            if a.get("affiliation", "").strip():
                L.append(f"\\address{{{esc(a['affiliation'])}}}")
            if a.get("email", "").strip():
                L.append(f"\\email{{{esc(a['email'])}}}")
        if msc:
            sec = f"; Secondary {', '.join(msc[1:])}" if len(msc) > 1 else ""
            L.append(f"\\subjclass[2020]{{Primary {msc[0]}{sec}}}")
        if kw_list:
            L.append(f"\\keywords{{{', '.join(kw_list)}}}")
        L += open_doc
        if abstract:
            L += ["\\begin{abstract}", abstract, "\\end{abstract}", ""]
        L += ["\\maketitle", ""]
    elif tpl == "elsarticle":
        if prof.get("journal"):
            L.append(f"\\journal{{{esc(prof['journal'])}}}")
        L += open_doc + ["\\begin{frontmatter}", f"\\title{{{title}}}"]
        affils: list[str] = []
        for a in authors:
            aff = a.get("affiliation", "").strip()
            if aff and aff not in affils:
                affils.append(aff)
            mark = f"[{affils.index(aff) + 1}]" if aff else ""
            L.append(f"\\author{mark}{{{esc(a['name'])}}}")
            if a.get("email", "").strip():
                L.append(f"\\ead{{{esc(a['email'])}}}")
        L += [f"\\address[{i}]{{{esc(aff)}}}" for i, aff in enumerate(affils, 1)]
        if abstract:
            L += ["\\begin{abstract}", abstract, "\\end{abstract}"]
        if kw_list or msc:
            L.append("\\begin{keyword}")
            if kw_list:
                L.append(" \\sep ".join(kw_list))
            if msc:
                L.append("\\MSC[2020] " + " \\sep ".join(msc))
            L.append("\\end{keyword}")
        L += ["\\end{frontmatter}", ""]
    else:
        L.append(f"\\title{{{title}}}")
        names = " \\and ".join(
            esc(a["name"]) + (f"\\\\ \\small {esc(a['affiliation'])}" if a.get("affiliation", "").strip() else "")
            + (f"\\\\ \\small \\texttt{{{esc(a['email'])}}}" if a.get("email", "").strip() else "")
            for a in authors)
        L += [f"\\author{{{names}}}", "\\date{}"]
        L += open_doc + ["\\maketitle", ""]
        if abstract:
            L += ["\\begin{abstract}", abstract, "\\end{abstract}", ""]
        if kw_list:
            L.append(f"\\noindent\\textbf{{Keywords.}} {', '.join(kw_list)}\\par")
        if msc:
            L.append(f"\\noindent\\textbf{{MSC 2020.}} {', '.join(msc)}\\par")
        L.append("")

    if paper.get("intro"):
        if markers:
            L.append("%@block intro")
        L += ["\\section{Introduction}", "", _FIG_RE.sub(lambda m: figure_latex(m.group(1), figs), paper["intro"].strip()), ""]
    L.append(blocks_to_latex(paper.get("blocks", []), markers=markers, figs=figs))
    for head, text in statement_sections(paper, prof):
        L += ["", f"\\section*{{{head}}}", esc(text)]
    if refs:
        labels = reference_labels(refs, "numeric" if tpl == "elsarticle" else prof.get("ref_style", "numeric"))
        widest = max(labels, key=len) if labels else "9"
        if markers:
            L.append("%@block refs")
        L += ["", f"\\begin{{thebibliography}}{{{widest if not widest.isdigit() else '9' * len(widest)}}}", ""]
        for p, lab in zip(refs, labels):
            L += [reference_latex(p, lab), ""]
        L.append("\\end{thebibliography}")
    L += ["", "\\end{document}", ""]
    return "\n".join(L)


def lint(paper: dict) -> list[dict]:
    issues = []
    for part in ("abstract", "intro"):
        for prob in check_balance(paper.get(part) or ""):
            issues.append({"block": part, "message": prob})
        if re.search(r"(?<!\\)%", paper.get(part) or ""):
            issues.append({"block": part, "message": "an unescaped % hides the rest of its line; write \\%"})
    for b in paper.get("blocks", []):
        for prob in check_balance(b.get("text") or b.get("title") or ""):
            issues.append({"block": b.get("id"), "message": prob})
        if re.search(r"(?<!\\)%", b.get("text") or ""):
            issues.append({"block": b.get("id"), "message": "an unescaped % hides the rest of its line; write \\%"})
        if "[?" in (b.get("text") or ""):
            issues.append({"block": b.get("id"), "message": "contains an unresolved [?] marker from the transcription"})
    return issues


def find_engine() -> str | None:
    for exe in ("pdflatex", "tectonic", "xelatex", "lualatex"):
        if shutil.which(exe):
            return exe
    return None


_FLAGS: dict[str, list[str]] = {}


def engine_flags(engine: str) -> list[str]:
    """MiKTeX (the usual LaTeX on Windows) can fetch a missing package or class by itself, but only when told
    it may do so without asking; otherwise it opens a dialog nobody sees and the run hangs."""
    if engine not in _FLAGS:
        flags: list[str] = []
        try:
            r = subprocess.run([engine, "--version"], capture_output=True, timeout=20, stdin=subprocess.DEVNULL)
            if b"miktex" in (r.stdout or b"").lower():
                flags = ["-enable-installer"]
        except (subprocess.TimeoutExpired, OSError):
            pass
        _FLAGS[engine] = flags
    return _FLAGS[engine]


def render_tikz(code: str, timeout: int = 300) -> tuple[bytes | None, str]:
    """Compile one TikZ picture and return it as a PNG (or None and the reason)."""
    engine = find_engine()
    if engine not in ("pdflatex", "xelatex", "lualatex"):
        return None, "no LaTeX engine on this computer"
    macros = "\n".join(f"\\providecommand{{{k}}}{{{v}}}" for k, v in MACROS.items())
    doc = ("\\documentclass[11pt]{article}\n\\usepackage{amsmath,amssymb}\n\\usepackage{tikz}\n"
           f"\\usetikzlibrary{{{TIKZ_LIBS}}}\n{macros}\n\\pagestyle{{empty}}\n\\begin{{document}}\n\\noindent\n"
           + code.strip() + "\n\\end{document}\n")
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as d:
        dp = Path(d)
        (dp / "fig.tex").write_text(doc, encoding="utf-8")
        try:
            r = subprocess.run([engine, *engine_flags(engine), "-interaction=nonstopmode", "-file-line-error", "fig.tex"],
                               cwd=d, capture_output=True, timeout=timeout, stdin=subprocess.DEVNULL)
        except (subprocess.TimeoutExpired, OSError) as e:
            return None, "LaTeX took too long" if isinstance(e, subprocess.TimeoutExpired) else type(e).__name__
        log = (r.stdout or b"").decode("utf-8", "ignore")
        errs = re.findall(r"(?m)^(?:\./)?fig\.tex:\d+:\s*(.+)$", log) or re.findall(r"(?m)^! (.+)$", log)
        pdf_path = dp / "fig.pdf"
        if errs or not pdf_path.exists():
            return None, "; ".join(e.strip() for e in errs[:3]) or "no output"
        try:
            import pypdfium2 as pdfium
            from PIL import Image, ImageChops
            pdf = pdfium.PdfDocument(pdf_path.read_bytes())
            img = pdf[0].render(scale=2.6).to_pil().convert("RGB")
            pdf.close()
            box = ImageChops.difference(img, Image.new("RGB", img.size, "white")).getbbox()
            if not box:
                return None, "the picture is empty"
            pad = 14
            img = img.crop((max(0, box[0] - pad), max(0, box[1] - pad), min(img.width, box[2] + pad), min(img.height, box[3] + pad)))
            buf = io.BytesIO()
            img.save(buf, "PNG")
            return buf.getvalue(), ""
        except Exception as e:  # noqa: BLE001
            return None, f"could not render ({type(e).__name__})"


def compile_pdf(tex: str, timeout: int = 300, files: dict | None = None) -> dict:
    """Compile if a LaTeX engine is installed.
    Returns {ok, pdf, errors:[{line, message}], engine, undefined:[macro names], missing:[file names], pages}."""
    engine = find_engine()
    if not engine:
        return {"ok": False, "engine": None, "errors": [], "pdf": None, "undefined": [], "missing": [], "pages": None}
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as d:     # Windows may still hold main.log
        dp = Path(d)
        (dp / "main.tex").write_text(tex, encoding="utf-8")
        for name, data in (files or {}).items():
            target = dp / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        cmd = [engine, "main.tex"] if engine == "tectonic" else \
            [engine, *engine_flags(engine), "-interaction=nonstopmode", "-file-line-error", "main.tex"]
        log = ""
        try:
            for _ in range(1 if engine == "tectonic" else 2):
                r = subprocess.run(cmd, cwd=d, capture_output=True, timeout=timeout, stdin=subprocess.DEVNULL)
                log = (r.stdout or b"").decode("utf-8", "ignore") + (r.stderr or b"").decode("utf-8", "ignore")
        except (subprocess.TimeoutExpired, OSError) as e:
            return {"ok": False, "engine": engine, "errors": [{"line": 0, "message": f"{type(e).__name__}"}], "pdf": None,
                    "undefined": [], "missing": [], "pages": None}
        errors = []
        for m in re.finditer(r"(?m)^(?:\./)?main\.tex:(\d+):\s*(.+)$", log):
            errors.append({"line": int(m.group(1)), "message": m.group(2).strip()[:200]})
        for m in re.finditer(r"(?m)^! (.+)\n(?:.*\n){0,8}?l\.(\d+)", log):
            errors.append({"line": int(m.group(2)), "message": m.group(1).strip()[:200]})
        errors = [e for e in errors if "Emergency stop" not in e["message"] and "Fatal error" not in e["message"]] or errors
        if not errors:                       # failures TeX reports without a line number
            for m in re.finditer(r"(?m)^! (File ended.*|.*Runaway.*|Emergency stop.*|.*[Ee]rror.*)$", log):
                errors.append({"line": 0, "message": m.group(1).strip()[:200]})
        pdf = (dp / "main.pdf").read_bytes() if (dp / "main.pdf").exists() else None
        if pdf is None and not errors:
            errors.append({"line": 0, "message": "LaTeX stopped without producing a PDF"})
        # a command that is defined nowhere: named on the line TeX prints under the error, as its last control word
        undefined: list[str] = []
        for m in re.finditer(r"Undefined control sequence\.[^\n]*\n(?:[^\n]*\n){0,3}?l\.\d+ ([^\n]*)", log):
            names = re.findall(r"\\([A-Za-z]+)", m.group(1))
            if names and names[-1] not in undefined:
                undefined.append(names[-1])
        missing = list(dict.fromkeys(re.findall(r"File `([^']+)' not found", log)))
        pages = None
        if pdf:
            try:
                import pypdfium2 as pdfium
                doc = pdfium.PdfDocument(pdf)
                pages = len(doc)
                doc.close()
            except Exception:  # noqa: BLE001
                pages = None
        return {"ok": pdf is not None and not errors, "engine": engine, "errors": errors[:12], "pdf": pdf,
                "undefined": undefined, "missing": missing, "pages": pages}


def block_at_line(tex: str, line: int) -> str | None:
    """Which block produced a given line of the marked-up LaTeX file."""
    current = None
    for n, l in enumerate(tex.split("\n"), 1):
        m = re.match(r"^%@block (\S+)", l)
        if m:
            current = m.group(1)
        if n >= line:
            return current
    return current


def make_zip(files: dict[str, bytes | str]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in files.items():
            z.writestr(name, data if isinstance(data, bytes) else data.encode("utf-8"))
    return buf.getvalue()


