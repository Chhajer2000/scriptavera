def build_tex(paper: dict, refs: list[dict], profile: dict | str | None = None, markers: bool = False) -> str:
    """The complete LaTeX file, generated by code. `profile` holds the journal's requirements (see journals.py);
    its "template" picks the class: amsart, article or elsarticle."""
    if isinstance(profile, str):
        profile = {"template": profile}
    prof = {**(paper.get("profile") or {}), **(profile or {})}
    tpl = prof.get("template") if prof.get("template") in ("amsart", "article", "elsarticle") else "amsart"
    anonymous = bool(prof.get("anonymous"))
    title = escape_specials(clean_fragment(paper.get("title") or "Untitled"))
    authors = [] if anonymous else [a for a in paper.get("authors") or [] if a.get("name", "").strip()]
    esc = lambda x: latex_escape(x, keep_math=False)                                     # noqa: E731
    L: list[str] = []
    if tpl == "amsart":
        L.append("\\documentclass[11pt,reqno]{amsart}")
    elif tpl == "elsarticle":
        L.append("\\documentclass[preprint,11pt]{elsarticle}")
    else:
        L.append("\\documentclass[11pt]{article}")
    L += [
        "\\usepackage[T1]{fontenc}", "\\usepackage[utf8]{inputenc}",
        "\\IfFileExists{lmodern.sty}{\\usepackage{lmodern}}{}",
        "\\usepackage{amsmath,amssymb,amsthm,mathtools}", "\\usepackage{enumitem}", "\\usepackage{xcolor}",
        "\\PassOptionsToPackage{hyphens}{url}",
    ]
    everything = "\n".join([paper.get("abstract") or "", paper.get("intro") or ""]
                           + [(b.get("text") or "") + " " + (b.get("title") or "") for b in paper.get("blocks", [])])
    L += needed_packages(everything)            # \cancel needs the package cancel, \mathscr needs mathrsfs, …
    L += [
        "\\usepackage[colorlinks=true,linkcolor=blue!55!black,citecolor=blue!55!black,urlcolor=blue!55!black]{hyperref}",
    ]
    figs = paper.get("figures") or {}
    used_figs = figures_used(paper)
    if used_figs:
        L.append("\\usepackage{graphicx}")
        if any(figs[f]["mode"] == "tikz" for f in used_figs):
            L += ["\\usepackage{tikz}", f"\\usetikzlibrary{{{TIKZ_LIBS}}}"]
    if tpl == "article":
        L.append("\\usepackage[margin=1in]{geometry}")
    if prof.get("double_spacing"):
        L += ["\\usepackage{setspace}", "\\doublespacing"]
    if prof.get("line_numbers"):
        L.append("\\usepackage{lineno}")
    L += ["", "\\theoremstyle{plain}", "\\newtheorem{theorem}{Theorem}[section]"]
    L += [f"\\newtheorem{{{e}}}[theorem]{{{THEOREM_ENVS[e]}}}" for e in _PLAIN if e != "theorem"]
    L.append("\\theoremstyle{definition}")
    L += [f"\\newtheorem{{{e}}}[theorem]{{{THEOREM_ENVS[e]}}}" for e in _DEFN]
    L.append("\\theoremstyle{remark}")
    L += [f"\\newtheorem{{{e}}}[theorem]{{{THEOREM_ENVS[e]}}}" for e in _REMARK]
    body_text = (paper.get("intro") or "") + "\n" + "\n".join((b.get("text") or "") for b in paper.get("blocks", []))
    used = set(re.findall(r"\\begin\{([A-Za-z]+)\*?\}", body_text)) | {b.get("env") for b in paper.get("blocks", []) if b.get("env")}
    extra = sorted(e for e in used if e and e not in THEOREM_ENVS and e not in _KNOWN_ENVS and e.isalpha())
    if extra:                                    # an environment the writer used that LaTeX would not know
        L.append("\\theoremstyle{definition}")
        L += [f"\\newtheorem{{{e}}}[theorem]{{{e.capitalize()}}}" for e in extra]
    L += list(paper.get("source_preamble") or [])        # typed notes: the author's own macros and packages
    L += [f"\\providecommand{{{k}}}{{{v}}}" for k, v in {**MACROS, **(paper.get("macros") or {})}.items()]
    L += ["\\newenvironment{figurenote}{\\par\\smallskip\\noindent\\textit{Figure in the notes.}\\ }{\\par\\smallskip}", ""]

    kw_list = [latex_escape(k) for k in paper.get("keywords") or []]
    msc = [m for m in paper.get("msc") or [] if m]
    abstract = escape_specials(clean_fragment(paper.get("abstract") or ""), underscore=False)
    open_doc = ["", "\\begin{document}"] + (["\\linenumbers"] if prof.get("line_numbers") else []) + [""]

    if tpl == "amsart":
        L.append(f"\\title{{{title}}}")
        for a in authors:
            L.append(f"\\author{{{esc(a['name'])}}}")
            if a.get("affiliation", "").strip():
                L.append(f"\\address{{{esc(a['affiliation'])}}}")
            if a.get("email", "").strip():
                L.append(f"\\email{{{esc(a['email'])}}}")
        if msc:
            sec = f"; Secondary {', '.join(msc[1:])}" if len(msc) > 1 else ""
            L.append(f"\\subjclass[2020]{{Primary {msc[0]}{sec}}}")
        if kw_list:
            L.append(f"\\keywords{{{', '.join(kw_list)}}}")
        L += open_doc
        if abstract:
            L += ["\\begin{abstract}", abstract, "\\end{abstract}", ""]
        L += ["\\maketitle", ""]
    elif tpl == "elsarticle":
        if prof.get("journal"):
            L.append(f"\\journal{{{esc(prof['journal'])}}}")
        L += open_doc + ["\\begin{frontmatter}", f"\\title{{{title}}}"]
        affils: list[str] = []
        for a in authors:
            aff = a.get("affiliation", "").strip()
            if aff and aff not in affils:
                affils.append(aff)
            mark = f"[{affils.index(aff) + 1}]" if aff else ""
            L.append(f"\\author{mark}{{{esc(a['name'])}}}")
            if a.get("email", "").strip():
                L.append(f"\\ead{{{esc(a['email'])}}}")
        L += [f"\\address[{i}]{{{esc(aff)}}}" for i, aff in enumerate(affils, 1)]
        if abstract:
            L += ["\\begin{abstract}", abstract, "\\end{abstract}"]
        if kw_list or msc:
            L.append("\\begin{keyword}")
            if kw_list:
                L.append(" \\sep ".join(kw_list))
            if msc:
                L.append("\\MSC[2020] " + " \\sep ".join(msc))
            L.append("\\end{keyword}")
        L += ["\\end{frontmatter}", ""]
    else:
        L.append(f"\\title{{{title}}}")
        names = " \\and ".join(
            esc(a["name"]) + (f"\\\\ \\small {esc(a['affiliation'])}" if a.get("affiliation", "").strip() else "")
            + (f"\\\\ \\small \\texttt{{{esc(a['email'])}}}" if a.get("email", "").strip() else "")
            for a in authors)
        L += [f"\\author{{{names}}}", "\\date{}"]
        L += open_doc + ["\\maketitle", ""]
        if abstract:
            L += ["\\begin{abstract}", abstract, "\\end{abstract}", ""]
        if kw_list:
            L.append(f"\\noindent\\textbf{{Keywords.}} {', '.join(kw_list)}\\par")
        if msc:
            L.append(f"\\noindent\\textbf{{MSC 2020.}} {', '.join(msc)}\\par")
        L.append("")

    if paper.get("intro"):
        if markers:
            L.append("%@block intro")
        L += ["\\section{Introduction}", "", _FIG_RE.sub(lambda m: figure_latex(m.group(1), figs), paper["intro"].strip()), ""]
    L.append(blocks_to_latex(paper.get("blocks", []), markers=markers, figs=figs))
    for head, text in statement_sections(paper, prof):
        L += ["", f"\\section*{{{head}}}", esc(text)]
    if paper.get("cite_software"):                  # last before the references, as Elsevier asks
        L += ["", f"\\section*{{{software_heading(prof)}}}", software_statement(paper)]
    if refs:
        labels = reference_labels(refs, "numeric" if tpl == "elsarticle" else prof.get("ref_style", "numeric"))
        widest = max(labels, key=len) if labels else "9"
        if markers:
            L.append("%@block refs")
        L += ["", f"\\begin{{thebibliography}}{{{widest if not widest.isdigit() else '9' * len(widest)}}}", ""]
        for p, lab in zip(refs, labels):
            L += [reference_latex(p, lab), ""]
        L.append("\\end{thebibliography}")
    L += ["", "\\end{document}", ""]
    return "\n".join(L)


def lint(paper: dict) -> list[dict]:
    issues = []
    for part in ("abstract", "intro"):
        for prob in check_balance(paper.get(part) or ""):
            issues.append({"block": part, "message": prob})
        if re.search(r"(?<!\\)%", paper.get(part) or ""):
            issues.append({"block": part, "message": "an unescaped % hides the rest of its line; write \\%"})
    for b in paper.get("blocks", []):
        for prob in check_balance(b.get("text") or b.get("title") or ""):
            issues.append({"block": b.get("id"), "message": prob})
        if re.search(r"(?<!\\)%", b.get("text") or ""):
            issues.append({"block": b.get("id"), "message": "an unescaped % hides the rest of its line; write \\%"})
        if "[?" in (b.get("text") or ""):
            issues.append({"block": b.get("id"), "message": "contains an unresolved [?] marker from the transcription"})
    return issues


def find_engine() -> str | None:
    for exe in ("pdflatex", "tectonic", "xelatex", "lualatex"):
        if shutil.which(exe):
            return exe
    return None


_FLAGS: dict[str, list[str]] = {}


def engine_flags(engine: str) -> list[str]:
    """MiKTeX (the usual LaTeX on Windows) can fetch a missing package or class by itself, but only when told
    it may do so without asking; otherwise it opens a dialog nobody sees and the run hangs."""
    if engine not in _FLAGS:
        flags: list[str] = []
        try:
            r = subprocess.run([engine, "--version"], capture_output=True, timeout=20, stdin=subprocess.DEVNULL)
            if b"miktex" in (r.stdout or b"").lower():
                flags = ["-enable-installer"]
        except (subprocess.TimeoutExpired, OSError):
            pass
        _FLAGS[engine] = flags
    return _FLAGS[engine]


def render_tikz(code: str, timeout: int = 300) -> tuple[bytes | None, str]:
    """Compile one TikZ picture and return it as a PNG (or None and the reason)."""
    engine = find_engine()
    if engine not in ("pdflatex", "xelatex", "lualatex"):
        return None, "no LaTeX engine on this computer"
    macros = "\n".join(f"\\providecommand{{{k}}}{{{v}}}" for k, v in MACROS.items())
    doc = ("\\documentclass[11pt]{article}\n\\usepackage{amsmath,amssymb}\n\\usepackage{tikz}\n"
           f"\\usetikzlibrary{{{TIKZ_LIBS}}}\n{macros}\n\\pagestyle{{empty}}\n\\begin{{document}}\n\\noindent\n"
           + code.strip() + "\n\\end{document}\n")
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as d:
        dp = Path(d)
        (dp / "fig.tex").write_text(doc, encoding="utf-8")
        try:
            r = subprocess.run([engine, *engine_flags(engine), "-interaction=nonstopmode", "-file-line-error", "fig.tex"],
                               cwd=d, capture_output=True, timeout=timeout, stdin=subprocess.DEVNULL)
        except (subprocess.TimeoutExpired, OSError) as e:
            return None, "LaTeX took too long" if isinstance(e, subprocess.TimeoutExpired) else type(e).__name__
        log = (r.stdout or b"").decode("utf-8", "ignore")
        errs = re.findall(r"(?m)^(?:\./)?fig\.tex:\d+:\s*(.+)$", log) or re.findall(r"(?m)^! (.+)$", log)
        pdf_path = dp / "fig.pdf"
        if errs or not pdf_path.exists():
            return None, "; ".join(e.strip() for e in errs[:3]) or "no output"
        try:
            import pypdfium2 as pdfium
            from PIL import Image, ImageChops
            pdf = pdfium.PdfDocument(pdf_path.read_bytes())
            img = pdf[0].render(scale=2.6).to_pil().convert("RGB")
            pdf.close()
            box = ImageChops.difference(img, Image.new("RGB", img.size, "white")).getbbox()
            if not box:
                return None, "the picture is empty"
            pad = 14
            img = img.crop((max(0, box[0] - pad), max(0, box[1] - pad), min(img.width, box[2] + pad), min(img.height, box[3] + pad)))
            buf = io.BytesIO()
            img.save(buf, "PNG")
            return buf.getvalue(), ""
        except Exception as e:  # noqa: BLE001
            return None, f"could not render ({type(e).__name__})"


def measure_tex(snippets: list[str], timeout: int = 120) -> list[tuple[float, float] | None]:
    """The typeset size (width, height with depth), in points, of each piece of text as a label of a TikZ picture
    sets it (inline, in the document font of render_tikz), from one compile. None for a piece that does not compile,
    and for all of them when no LaTeX engine is installed."""
    engine = find_engine()
    if engine not in ("pdflatex", "xelatex", "lualatex") or not snippets:
        return [None] * len(snippets)
    macros = "\n".join(f"\\providecommand{{{k}}}{{{v}}}" for k, v in MACROS.items())
    body = []
    for i, t in enumerate(snippets):
        body.append(f"\\sbox\\lblbox{{\\begin{{tabular}}{{@{{}}c@{{}}}}{t}\\end{{tabular}}}}"
                    f"\\typeout{{SIZE {i} \\the\\wd\\lblbox\\space\\the\\ht\\lblbox\\space\\the\\dp\\lblbox}}")
    doc = ("\\documentclass[11pt]{article}\n\\usepackage{amsmath,amssymb}\n" + macros + "\n\\newsavebox\\lblbox\n"
           "\\begin{document}\n" + "\n".join(body) + "\n\\end{document}\n")
    out: list = [None] * len(snippets)
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as d:
        (Path(d) / "m.tex").write_text(doc, encoding="utf-8")
        try:
            r = subprocess.run([engine, *engine_flags(engine), "-interaction=nonstopmode", "-draftmode", "m.tex"],
                               cwd=d, capture_output=True, timeout=timeout, stdin=subprocess.DEVNULL)
        except (subprocess.TimeoutExpired, OSError):
            return out
        log = (r.stdout or b"").decode("utf-8", "ignore")
    for m in re.finditer(r"(?m)^SIZE (\d+) ([\d.]+)pt ([\d.]+)pt ([\d.]+)pt", log):
        i = int(m.group(1))
        out[i] = (float(m.group(2)), float(m.group(3)) + float(m.group(4)))
    if "! " in log:                                   # an error: a piece measured after it may be wrong, keep none
        return [None] * len(snippets)
    return out


def compile_pdf(tex: str, timeout: int = 300, files: dict | None = None) -> dict:
    """Compile if a LaTeX engine is installed.
    Returns {ok, pdf, errors:[{line, message}], engine, undefined:[macro names], missing:[file names], pages}."""
    engine = find_engine()
    if not engine:
        return {"ok": False, "engine": None, "errors": [], "pdf": None, "undefined": [], "missing": [], "pages": None}
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as d:     # Windows may still hold main.log
        dp = Path(d)
        (dp / "main.tex").write_text(tex, encoding="utf-8")
        for name, data in (files or {}).items():
            target = dp / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        cmd = [engine, "main.tex"] if engine == "tectonic" else \
            [engine, *engine_flags(engine), "-interaction=nonstopmode", "-file-line-error", "main.tex"]
        log = ""
        try:
            for _ in range(1 if engine == "tectonic" else 2):
                r = subprocess.run(cmd, cwd=d, capture_output=True, timeout=timeout, stdin=subprocess.DEVNULL)
                log = (r.stdout or b"").decode("utf-8", "ignore") + (r.stderr or b"").decode("utf-8", "ignore")
        except (subprocess.TimeoutExpired, OSError) as e:
            return {"ok": False, "engine": engine, "errors": [{"line": 0, "message": f"{type(e).__name__}"}], "pdf": None,
                    "undefined": [], "missing": [], "pages": None}
        errors = []
        for m in re.finditer(r"(?m)^(?:\./)?main\.tex:(\d+):\s*(.+)$", log):
            errors.append({"line": int(m.group(1)), "message": m.group(2).strip()[:200]})
        for m in re.finditer(r"(?m)^! (.+)\n(?:.*\n){0,8}?l\.(\d+)", log):
            errors.append({"line": int(m.group(2)), "message": m.group(1).strip()[:200]})
        errors = [e for e in errors if "Emergency stop" not in e["message"] and "Fatal error" not in e["message"]] or errors
        if not errors:                       # failures TeX reports without a line number
            for m in re.finditer(r"(?m)^! (File ended.*|.*Runaway.*|Emergency stop.*|.*[Ee]rror.*)$", log):
                errors.append({"line": 0, "message": m.group(1).strip()[:200]})
        pdf = (dp / "main.pdf").read_bytes() if (dp / "main.pdf").exists() else None
        if pdf is None and not errors:
            errors.append({"line": 0, "message": "LaTeX stopped without producing a PDF"})
        # a command that is defined nowhere: named on the line TeX prints under the error, as its last control word
        undefined: list[str] = []
        for m in re.finditer(r"Undefined control sequence\.[^\n]*\n(?:[^\n]*\n){0,3}?l\.\d+ ([^\n]*)", log):
            names = re.findall(r"\\([A-Za-z]+)", m.group(1))
            if names and names[-1] not in undefined:
                undefined.append(names[-1])
        missing = list(dict.fromkeys(re.findall(r"File `([^']+)' not found", log)))
        # lines wider than the page: "detected at line N" is a displayed formula, "in paragraph" running text
        overfull = [{"line": int(m.group(3)), "pt": float(m.group(1)), "too_wide": f"{float(m.group(1)):.1f}pt",
                     "math": m.group(2).startswith("detected")}
                    for m in re.finditer(r"Overfull \\hbox \((\d+(?:\.\d+)?)pt too wide\) (detected at line|in paragraph "
                                         r"at lines) (\d+)", log) if float(m.group(1)) >= 1.0]
        pages = None
        if pdf:
            try:
                import pypdfium2 as pdfium
                doc = pdfium.PdfDocument(pdf)
                pages = len(doc)
                doc.close()
            except Exception:  # noqa: BLE001
                pages = None
        return {"ok": pdf is not None and not errors, "engine": engine, "errors": errors[:12], "pdf": pdf,
                "undefined": undefined, "missing": missing, "pages": pages, "overfull": overfull}


# ------------------------------------------------- formulas wider than the page

_REL_CMDS = {"leqslant", "geqslant", "Longleftrightarrow", "Leftrightarrow", "Longrightarrow", "Rightarrow", "implies",
             "iff", "coloneqq", "subseteq", "supseteq", "subsetneq", "approx", "equiv", "simeq", "cong", "leq", "geq",
             "neq", "le", "ge", "ne", "sim", "subset", "supset", "to", "mapsto", "in", "ll", "gg", "propto"}
_OPERATOR_CMDS = {"cdot", "times", "pm", "mp", "quad", "qquad", "colon", "mid", "setminus", "cup", "cap", "circ"}


def _break_points(body: str) -> list[tuple[int, str, int]]:
    """Where a one-line formula may be broken: (position, 'rel' or 'bin', level). Level 0 is the top level of the
    formula; level 1 is directly inside one \\left…\\right at the top level, which is broken as \\right. … \\left.
    Nothing inside braces or a nested environment is a break point."""
    out: list[tuple[int, str, int]] = []
    i, n = 0, len(body)
    brace, env, paren = 0, 0, 0                    # paren: plain ( ) and [ ], never broken inside
    lr: list[int] = []
    prev = ""                                      # 'operand' when a + or - here would be binary
    while i < n:
        c = body[i]
        if c == "\\":
            m = re.match(r"\\([A-Za-z]+)|\\.", body[i:])
            tok, name = m.group(0), m.group(1)
            if name in ("left", "right"):
                d = re.match(r"\s*(\\[A-Za-z]+|\\.|.)", body[i + len(tok):])
                if name == "left":
                    lr.append(brace)
                elif lr:
                    lr.pop()
                i += len(tok) + (len(d.group(0)) if d else 0)
                prev = "op" if name == "left" else "operand"
                continue
            if name in ("begin", "end"):
                g = re.match(r"\{[^{}]*\}", body[i + len(tok):])
                env += 1 if name == "begin" else -1
                i += len(tok) + (len(g.group(0)) if g else 0)
                prev = "op" if name == "begin" else "operand"
                continue
            if name in _REL_CMDS:
                if brace == 0 and env == 0 and paren == 0 and len(lr) <= 1:
                    out.append((i, "rel", len(lr)))
                prev = "op"
            else:
                prev = "op" if (name in _OPERATOR_CMDS or not name) else "operand"
            i += len(tok)
            continue
        if c == "{":
            brace += 1
            prev = "op"
        elif c == "}":
            brace -= 1
            prev = "operand"
        elif c in "=<>":
            if brace == 0 and env == 0 and paren == 0 and len(lr) <= 1 and not (c == "=" and i and body[i - 1] == ":"):
                out.append((i - 1 if (c == "=" and i and body[i - 1] == ":") else i, "rel", len(lr)))
            prev = "op"
        elif c == ":" and i + 1 < n and body[i + 1] == "=":
            if brace == 0 and env == 0 and paren == 0 and len(lr) <= 1:
                out.append((i, "rel", len(lr)))
            i += 2
            prev = "op"
            continue
        elif c in "+-":
            if brace == 0 and env == 0 and paren == 0 and len(lr) <= 1 and prev == "operand":
                out.append((i, "bin", len(lr)))
            prev = "op"
        elif c in "([":
            paren += 1
            prev = "op"
        elif c in ")]":
            paren = max(0, paren - 1)
            prev = "operand"
        elif c in ",^_&":
            prev = "op"
        elif c in "|!'" or c.isalnum():
            prev = "operand"
        i += 1
    return out


def _top_level(body: str, s: str) -> bool:
    """Whether `s` (such as '\\\\' or '&') occurs outside braces and nested environments."""
    depth, env = 0, 0
    for m in re.finditer(r"\\begin\{[^{}]*\}|\\end\{[^{}]*\}|\\\\|\\.|[{}&]", body):
        t = m.group(0)
        if t.startswith("\\begin"):
            env += 1
        elif t.startswith("\\end"):
            env -= 1
        elif t == "{":
            depth += 1
        elif t == "}":
            depth -= 1
        elif t == s and depth == 0 and env == 0:
            return True
    return False


def _weight(tex: str) -> int:
    """Roughly how much of a formula is printed: command names, braces and spaces take no room."""
    return len(re.sub(r"\\[A-Za-z]+|[{}\s&]|\\[,;:!]", "", tex))


def _split_line(line: str, aligned: bool) -> tuple[str, str] | None:
    """One line of a formula broken in two near its middle, at a relation if possible, else at a + or -."""
    amp = -1
    if aligned:
        depth = 0
        for m in re.finditer(r"\\.|[{}&]", line):
            if m.group(0) == "{":
                depth += 1
            elif m.group(0) == "}":
                depth -= 1
            elif m.group(0) == "&" and depth == 0:
                amp = m.start()
                break
    head, body = (line[:amp + 1], line[amp + 1:]) if amp >= 0 else ("", line)
    pts = _break_points(body)
    rels = [p for p in pts if p[1] == "rel" and p[2] == 0]
    first = rels[0][0] if rels else None
    after = first if aligned else None             # aligned lines break after their first relation; multlined anywhere
    cands = [p for p in pts if (after is None or p[0] > after) and not (p[1] == "rel" and p[2] == 1)
             and min(_weight(body[:p[0]]), _weight(body[p[0]:])) >= max(5, 0.25 * _weight(body))]
    if _weight(body) < 20:                         # a formula this short is not what overflows a page
        return None
    if not cands:                                  # only breaks that leave a scrap on one line: better left as it is
        return None
    total = max(1, _weight(body))
    penalty = {("rel", 0): 0.0, ("bin", 0): 0.08, ("bin", 1): 0.16}
    q, kind, level = min(cands, key=lambda p: abs(_weight(body[:p[0]]) - total / 2) / total + penalty.get((p[1], p[2]), 1))
    left, right = body[:q].rstrip(), body[q:].lstrip()
    if level == 1:
        left, right = left + r" \right.", r"\left. " + right
    if aligned and amp < 0 and first is not None:          # first break of a one-line formula: align at its relation
        left = body[:first].rstrip() + " &" + body[first:q].rstrip() + (r" \right." if level == 1 else "")
    if aligned:
        return head + left, ("&" if kind == "rel" else r"&\quad ") + right
    return head + left, right


def break_display(content: str) -> str | None:
    """A displayed formula too wide for the page, broken over lines the way it is done by hand: aligned at its
    first relation (split), or for a formula without one, multlined. A formula broken before is broken again at its
    longest line. None when it cannot be broken by rule (a single long term, or a formula already in several lines
    of the author's own)."""
    labels = "".join(re.findall(r"\\label\{[^{}]*\}|\\tag\*?\{[^{}]*\}", content))
    c = re.sub(r"\\label\{[^{}]*\}|\\tag\*?\{[^{}]*\}", "", content).strip()
    m = re.fullmatch(r"\\begin\{(split|multlined)\}(.*)\\end\{\1\}", c, re.S)
    if m:
        env = m.group(1)
        lines = [x.strip() for x in re.split(r"\\\\", m.group(2)) if x.strip()]
        k = max(range(len(lines)), key=lambda i: len(lines[i]))
        r = _split_line(lines[k], env == "split")
        if not r:
            return None
        lines[k:k + 1] = [r[0].strip(), r[1].strip()]
    else:
        if _top_level(c, "\\\\") or _top_level(c, "&"):
            return None
        pts = _break_points(c)
        env, r = "split", None
        if any(p[1] == "rel" and p[2] == 0 for p in pts):
            r = _split_line(c, True)
        if r is None:                              # no relation, or nothing to break after it: a long left side
            env, r = "multlined", _split_line(c, False)
        if not r:
            return None
        lines = [r[0].strip(), r[1].strip()]
    return (labels + "\n" if labels else "\n") + f"\\begin{{{env}}}\n" + " \\\\\n".join(lines) + f"\n\\end{{{env}}}\n"


_DISPLAY = re.compile(r"\\\[(.+?)\\\]|\$\$(.+?)\$\$|\\begin\{(equation\*?)\}(.+?)\\end\{\3\}", re.S)


def break_in_text(text: str, line: int) -> str | None:
    """The text with the displayed formula that ends on (0-based) `line` broken over lines; None if there is none
    there, or it cannot be broken by rule."""
    for m in _DISPLAY.finditer(text):
        a, b = text.count("\n", 0, m.start()), text.count("\n", 0, m.end())
        if not (a <= line <= b + 1):
            continue
        if m.group(1) is not None:
            inner, s, e = m.group(1), m.start(1), m.end(1)
        elif m.group(2) is not None:
            inner, s, e = m.group(2), m.start(2), m.end(2)
        else:
            inner, s, e = m.group(4), m.start(4), m.end(4)
        new = break_display(inner)
        if new is None:
            return None
        return text[:s] + new + text[e:]
    return None


def break_overfull(paper: dict, marked: str, overfull: list[dict]) -> bool:
    """Break the displayed formulas that LaTeX reported as wider than the page (`marked` is the file with
    %@block markers it compiled). Returns whether anything changed."""
    lines = marked.split("\n")
    starts = {m.group(1): n for n, l in enumerate(lines, 1) for m in [re.match(r"^%@block (\S+)", l)] if m}
    blocks = {b.get("id"): b for b in paper.get("blocks", [])}
    changed = False
    done: set[tuple[str, int]] = set()
    for o in overfull:
        if not o.get("math"):
            continue
        bid = block_at_line(marked, o["line"])
        if bid == "intro" and paper.get("intro"):
            key, text, offset = "intro", paper["intro"], starts["intro"] + 3
        elif bid in blocks and blocks[bid].get("text") and blocks[bid]["type"] not in ("section", "subsection"):
            b = blocks[bid]
            key, text = bid, b["text"]
            offset = starts[bid] + (2 if b["type"] in ("env", "proof", "figure") else 1)
        else:
            continue
        lead = text[:len(text) - len(text.lstrip())].count("\n")
        rel = o["line"] - offset + lead
        if (key, rel) in done:
            continue
        done.add((key, rel))
        new = break_in_text(text, rel)
        if not new:
            o["unbroken"] = True
            continue
        if key == "intro":
            paper["intro"] = new
        else:
            blocks[key]["text"] = new
        changed = True
    return changed


def block_at_line(tex: str, line: int) -> str | None:
    """Which block produced a given line of the marked-up LaTeX file."""
    current = None
    for n, l in enumerate(tex.split("\n"), 1):
        m = re.match(r"^%@block (\S+)", l)
        if m:
            current = m.group(1)
        if n >= line:
            return current
    return current


def make_zip(files: dict[str, bytes | str]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in files.items():
            z.writestr(name, data if isinstance(data, bytes) else data.encode("utf-8"))
    return buf.getvalue()


