def _math_span(tex: str, display: bool, ctx: dict) -> str:
    t = tex
    lab = re.search(r"\\label\{([^{}]+)\}", t)
    t = re.sub(r"\\label\{[^{}]+\}", "", t)
    t = re.sub(r"\\(nonumber|notag)\b", "", t)
    if lab and lab.group(1) in ctx.get("labels", {}) and "\\begin{equation}" in t:
        t = t.replace("\\end{equation}", f"\\tag{{{ctx['labels'][lab.group(1)]}}}\\end{{equation}}")
    t = re.sub(r"\\begin\{equation\}(.*?)\\end\{equation\}", lambda m: m.group(1) if "\\tag" not in m.group(1)
               else "\\begin{equation}" + m.group(1) + "\\end{equation}", t, flags=re.S)
    t = t.replace("eqnarray*", "align*").replace("eqnarray", "align")
    t = re.sub(r"\\(begin|end)\{(flalign|multline)\*?\}", r"\\\1{gather*}", t)
    cls = "math display" if display else "math"
    anchor = f' id="eq-{html.escape(lab.group(1))}"' if lab else ""
    return f'<span class="{cls}"{anchor} data-tex="{html.escape(t.strip(), quote=True)}"></span>'


def _replace_cmd(text: str, name: str, fn) -> str:
    """Apply fn(arg) to every \\name{arg}, honouring nested braces."""
    out, pos = [], 0
    pat = re.compile(r"\\" + name + r"\s*\{")
    while True:
        m = pat.search(text, pos)
        if not m:
            out.append(text[pos:])
            break
        g = find_group(text, m.end() - 1)
        if not g:
            out.append(text[pos:])
            break
        out.append(text[pos:m.start()])
        out.append(fn(g[0]))
        pos = g[1]
    return "".join(out)


def _link(url: str, label: str) -> str:
    """An external link, only for http(s) addresses and with the address safe inside an attribute."""
    raw = html.unescape(url).replace("\\%", "%").replace("\\#", "#").replace("\\_", "_").strip()
    if not re.match(r"^https?://", raw, re.I):
        return label
    return f'<a href="{html.escape(raw, quote=True)}" target="_blank" rel="noopener">{label}</a>'


def _cite_html(keys: str, opt: str, ctx: dict) -> str:
    parts = []
    for k in [x.strip() for x in keys.split(",") if x.strip()]:
        n = ctx.get("cite", {}).get(k)
        if n:
            parts.append(f'<a class="cite" href="#ref-{html.escape(k)}" data-key="{html.escape(k)}">{n}</a>')
        else:
            parts.append(f'<span class="cite missing" title="No reference with key {html.escape(k)}">?</span>')
    inner = ", ".join(parts)
    if opt:
        inner += ", " + opt
    return "[" + inner + "]"


def _text_html(t: str, ctx: dict) -> str:
    t = re.sub(r"(?<!\\)%.*", "", t)
    t = html.escape(t, quote=False)
    t = re.sub(r"\\cite[tp]?\s*(?:\[([^\]]*)\])?\s*\{([^{}]+)\}", lambda m: _cite_html(m.group(2), m.group(1) or "", ctx), t)
    q = lambda a: html.escape(html.unescape(a), quote=True)          # safe inside an attribute
    for name in ("eqref",):
        t = _replace_cmd(t, name, lambda a: f'(<a class="ref" href="#eq-{q(a)}">{ctx.get("labels", {}).get(a, "?")}</a>)')
    for name in ("ref", "cref", "Cref", "autoref"):
        t = _replace_cmd(t, name, lambda a: f'<a class="ref" href="#lbl-{q(a)}">{ctx.get("labels", {}).get(a, "?")}</a>')
    t = _replace_cmd(t, "label", lambda a: "")
    t = _replace_cmd(t, "footnote", lambda a: f" ({a})")
    t = _replace_cmd(t, "url", lambda a: _link(a, a))
    hm = re.compile(r"\\href\s*\{")
    while True:
        m = hm.search(t)
        if not m:
            break
        g1 = find_group(t, m.end() - 1)
        g2 = find_group(t, g1[1]) if g1 and g1[1] < len(t) and t[g1[1]] == "{" else None
        if not g1 or not g2:
            break
        t = t[:m.start()] + _link(g1[0], g2[0]) + t[g2[1]:]
    for _ in range(3):                                  # nested emphasis
        for name, tag in _TEXT_CMDS.items():
            close = tag.split(" ")[0]
            t = _replace_cmd(t, name, lambda a, tag=tag, close=close: f"<{tag}>{a}</{close}>")
    t = re.sub(r"\{\\(?:it|em)\s+([^{}]*)\}", r"<em>\1</em>", t)
    t = re.sub(r"\{\\bf\s+([^{}]*)\}", r"<strong>\1</strong>", t)

    def lists(m: re.Match) -> str:
        tag = "ul" if m.group(1) == "itemize" else "ol"
        body = re.sub(r"^\s*\[[^\]]*\]", "", m.group(2))
        items = re.split(r"\\item\b\s*(?:\[([^\]]*)\])?", body)
        out, k = [], 1
        while k < len(items):
            lab, content = items[k], items[k + 1] if k + 1 < len(items) else ""
            pre = f'<span class="item-label">{lab}</span> ' if lab else ""
            out.append(f"<li>{pre}{content.strip()}</li>")
            k += 2
        return f"<{tag}>" + "".join(out) + f"</{tag}>"

    for _ in range(3):
        t = re.sub(r"\\begin\{(itemize|enumerate)\}(.*?)\\end\{\1\}", lists, t, flags=re.S)
    t = re.sub(r"\\begin\{center\}(.*?)\\end\{center\}", r'<div class="center">\1</div>', t, flags=re.S)
    t = re.sub(r"\\begin\{quote\}(.*?)\\end\{quote\}", r"<blockquote>\1</blockquote>", t, flags=re.S)
    t = re.sub(r"\\(noindent|medskip|smallskip|bigskip|newpage|clearpage|par|centering|qedhere|indent)\b\s*", "", t)
    t = re.sub(r"\\[vh]space\*?\{[^{}]*\}", "", t)
    t = t.replace("\\qed", "∎")
    t = re.sub(r"\\\\(\[[^\]]*\])?", "<br>", t)
    t = re.sub(r"\\(ldots|dots|cdots)\b(\{\})?", "…", t)
    t = t.replace("---", "—").replace("--", "–").replace("``", "“").replace("''", "”")
    t = re.sub(r"\\(quad|qquad)\b", "&emsp;", t)
    t = re.sub(r"\\[,;:! ]", " ", t)
    t = t.replace("~", "&nbsp;")
    t = t.replace("\\&amp;", "&amp;").replace("\\%", "%").replace("\\#", "#").replace("\\_", "_")
    t = t.replace("\\$", "$").replace("\\{", "&#123;").replace("\\}", "&#125;").replace("\\S", "§")
    t = re.sub(r"\{\\(['`^\"~=.uvHckrd])\{?\\?([A-Za-z])\}?\}", lambda m: _accent(m.group(1), m.group(2)), t)
    t = re.sub(r"\\(['`^\"~])\{?\\?([A-Za-z])\}?", lambda m: _accent(m.group(1), m.group(2)), t)
    t = re.sub(r"\{\\(o|O|l|L|ss|ae|AE|oe|OE|aa|AA|i)\}", lambda m: _SPECIAL_BACK.get(m.group(1), m.group(1)), t)
    t = re.sub(r"(?<!\\)[{}]", "", t)                    # grouping braces carry no meaning in HTML
    return t


_SPECIAL_BACK = {"o": "ø", "O": "Ø", "l": "ł", "L": "Ł", "ss": "ß", "ae": "æ", "AE": "Æ", "oe": "œ", "OE": "Œ",
                 "aa": "å", "AA": "Å", "i": "ı"}
_COMBINING = {"'": "\u0301", "`": "\u0300", "^": "\u0302", '"': "\u0308", "~": "\u0303", "=": "\u0304",
              "u": "\u0306", "v": "\u030c", "c": "\u0327", "k": "\u0328", "r": "\u030a", ".": "\u0307",
              "H": "\u030b", "d": "\u0323"}


def _accent(mark: str, letter: str) -> str:
    import unicodedata
    return unicodedata.normalize("NFC", letter + _COMBINING.get(mark, ""))


def tex_to_html(text: str, ctx: dict, inline: bool = False) -> str:
    """Render LaTeX prose to HTML. Mathematics is left for KaTeX in the browser."""
    slots: list[str] = []
    assembled = []
    figs = ctx.get("figs") or {}
    text = _FIG_RE.sub(lambda m: "" if inline else f"\n\n\x00F{m.group(1)}\x00\n\n", text or "")
    for kind, c in split_math(text or ""):
        if kind == "text":
            assembled.append(c)
        else:
            slots.append(_math_span(c, kind != "inline", ctx))
            assembled.append(f"\x00M{len(slots) - 1}\x00")
    t = _text_html("".join(assembled), ctx)

    def restore(s: str) -> str:
        return re.sub(r"\x00M(\d+)\x00", lambda m: slots[int(m.group(1))], s)

    if inline:
        return restore(t.strip())
    paras = [p.strip() for p in re.split(r"\n\s*\n", t) if p.strip()]
    out = []
    for p in paras:
        fm = re.match(r"^\x00F(\w+)\x00$", p)
        if fm:
            f = figs.get(fm.group(1))
            if f and f.get("mode") in ("tikz", "orig") and ctx.get("fig_url"):
                num = ctx.get("labels", {}).get("fig:" + fm.group(1), "")
                cap = tex_to_html(f.get("caption") or "", ctx, inline=True)
                out.append(f'<figure class="p-fig" id="lbl-fig:{fm.group(1)}"><img src="{html.escape(ctx["fig_url"](fm.group(1), f["mode"]), quote=True)}" alt="Figure {num}">'
                           f'<figcaption><span class="fig-head">Figure {num}.</span> {cap}</figcaption></figure>')
            continue
        if re.match(r"^<(ul|ol|div|blockquote)", p):
            out.append(restore(p))
        else:
            out.append("<p>" + restore(p) + "</p>")
    return "\n".join(out)


def _author_line(authors: list[dict]) -> str:
    names = [a.get("name", "").strip() for a in authors if a.get("name", "").strip()]
    return ", ".join(names)


def format_authors(p: dict, latex: bool) -> str:
    names = []
    for a in (p.get("authors") or [])[:8]:
        initials = " ".join(x[0] + "." for x in re.split(r"[\s\-]+", a.get("given", "")) if x and x[0].isalpha())
        nm = (initials + " " + a.get("family", "")).strip()
        if nm:
            names.append(nm)
    if len(p.get("authors") or []) > 8:
        names.append("et al.")
    if not names:
        return ""
    s = ", ".join(names[:-1]) + (" and " if len(names) > 1 else "") + names[-1] if len(names) != 2 else " and ".join(names)
    return latex_escape(s, keep_math=False).replace(". ", ".~") if latex else s


def reference_links(p: dict) -> list[tuple[str, str]]:
    """(label, url) pairs for a reference: DOI first, then arXiv, then any other URL."""
    links = []
    if p.get("doi"):
        links.append((f"doi:{p['doi']}", f"https://doi.org/{p['doi']}"))
    if p.get("arxiv"):
        links.append((f"arXiv:{p['arxiv']}", f"https://arxiv.org/abs/{p['arxiv']}"))
    if not links and p.get("zbl"):
        links.append((f"Zbl {p['zbl']}", f"https://zbmath.org/?q=an:{p['zbl']}"))
    if not links and p.get("url"):
        links.append(("link", p["url"]))
    return links


def _venue_bits(p: dict) -> tuple[str, str, str, str]:
    venue = p.get("venue") or ""
    if not venue and p.get("arxiv"):
        venue = "Preprint"
    return venue, str(p.get("volume") or ""), str(p.get("issue") or ""), str(p.get("pages") or "")


def _where(p: dict, latex: bool) -> str:
    """'Journal 12 (2015), no. 3, 275-276.' in either markup."""
    e = (lambda x: latex_escape(x, keep_math=False)) if latex else html.escape
    if not p.get("venue") and p.get("journal_ref"):          # arXiv's free-form journal reference, used as given
        return e(p["journal_ref"]).rstrip(".") + "."
    venue, vol, issue, pages = _venue_bits(p)
    tail = e(venue)
    if vol:
        tail += (f" \\textbf{{{e(vol)}}}" if latex else f" <strong>{e(vol)}</strong>")
    if p.get("year"):
        tail += f" ({p['year']})"
    if issue:
        tail += (f", no.~{e(issue)}" if latex else f", no.&nbsp;{e(issue)}")
    if pages:
        tail += ", " + (e(pages) if latex else e(pages.replace("--", "–")))
    return tail.strip(" ,") + "."


def reference_labels(refs: list[dict], style: str = "numeric") -> list[str]:
    """The label of each reference: its number, or an alphabetic label such as [Sm15] or [AB20]."""
    if style != "alpha":
        return [str(i + 1) for i in range(len(refs))]
    from .util import ascii_fold
    base = []
    for p in refs:
        fams = [re.sub(r"[^A-Za-z]", "", ascii_fold(a.get("family") or a.get("given") or "")) for a in p.get("authors") or []]
        fams = [f for f in fams if f]
        if not fams:
            stem = re.sub(r"[^A-Za-z]", "", ascii_fold(p.get("title") or "Anon"))[:3].capitalize() or "Anon"
        elif len(fams) == 1:
            stem = fams[0][:3].capitalize()
        elif len(fams) <= 4:
            stem = "".join(f[0].upper() for f in fams)
        else:
            stem = "".join(f[0].upper() for f in fams[:3]) + "+"
        base.append(stem + (str(p["year"])[-2:] if p.get("year") else ""))
    out = []
    for i, lab in enumerate(base):
        if base.count(lab) > 1:
            lab += "abcdefghijklmnopqrstuvwxyz"[min(base[:i].count(lab), 25)]
        out.append(lab)
    return out


def reference_html(p: dict, label: str) -> str:
    bits = []
    au = format_authors(p, latex=False)
    if au:
        bits.append(html.escape(au) + ",")
    bits.append("<em>" + tex_to_html(p.get("title", ""), {}, inline=True) + "</em>,")
    bits.append(_where(p, latex=False))
    links = " ".join(f'<a class="ref-link" href="{html.escape(u)}" target="_blank" rel="noopener">{html.escape(l)}</a>'
                     for l, u in reference_links(p))
    return (f'<li id="ref-{html.escape(p["key"])}"><span class="ref-label">[{html.escape(label)}]</span> '
            f'<span class="ref-text">' + " ".join(bits) + f"</span> {links}</li>")


def reference_latex(p: dict, label: str = "") -> str:
    s = ""
    au = format_authors(p, latex=True)
    if au:
        s += au + ", "
    s += "\\emph{" + latex_escape(p.get("title", "")) + "}, "
    s += _where(p, latex=True)
    for name, url in reference_links(p):
        safe_url = url.replace("%", "\\%").replace("#", "\\#")
        s += f" \\href{{{safe_url}}}{{{latex_escape(name, keep_math=False)}}}."
    opt = f"[{label}]" if label and not label.isdigit() else ""
    return f"\\bibitem{opt}{{{p['key']}}} {s}"


def reference_bibtex(p: dict) -> str:
    venue, vol, issue, pages = _venue_bits(p)
    kind = "article" if p.get("venue") and "arxiv" not in p["venue"].lower() else "misc"
    fields = [("author", " and ".join((a.get("family", "") + ", " + a.get("given", "")).strip(", ")
                                        for a in p.get("authors") or [])),
              ("title", "{" + (p.get("title") or "") + "}"),
              ("journal" if kind == "article" else "howpublished", venue),
              ("volume", vol), ("number", issue), ("pages", pages), ("year", str(p.get("year") or "")),
              ("doi", p.get("doi") or ""), ("eprint", p.get("arxiv") or ""),
              ("archivePrefix", "arXiv" if p.get("arxiv") else ""),
              ("url", reference_links(p)[0][1] if reference_links(p) else "")]
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields if v)
    return f"@{kind}{{{p['key']},\n{body}\n}}"


STATEMENTS = (("ack", "Acknowledgements"), ("funding", "Funding"), ("competing", "Competing interests"),
              ("data", "Data availability"))


def statement_sections(paper: dict, prof: dict | None = None) -> list[tuple[str, str]]:
    """The author's own statements, as headings with their text. Nothing here is ever written by a model.
    In an anonymous manuscript the two that identify the author are left out."""
    prof = prof if prof is not None else (paper.get("profile") or {})
    st = paper.get("statements") or {}
    out = []
    for key, head in STATEMENTS:
        text = re.sub(r"\s+", " ", str(st.get(key) or "")).strip()
        if text and not (prof.get("anonymous") and key in ("ack", "funding")):
            out.append((head, text))
    return out


def render_html(paper: dict, refs: list[dict], fig_url=None) -> str:
    """The paper as an HTML fragment (title to references) for the preview and the export."""
    labels = number_blocks(paper)
    prof = paper.get("profile") or {}
    ref_labels = reference_labels(refs, prof.get("ref_style", "numeric"))
    ctx = {"labels": labels, "cite": {p["key"]: ref_labels[i] for i, p in enumerate(refs)},
           "figs": paper.get("figures") or {}, "fig_url": fig_url}
    out = ['<article class="paper">']
    out.append(f'<h1 class="p-title">{tex_to_html(paper.get("title") or "Untitled", ctx, inline=True)}</h1>')
    au = [] if prof.get("anonymous") else (paper.get("authors") or [])
    if au:
        out.append('<div class="p-authors">' + html.escape(_author_line(au)) + "</div>")
        aff = [a.get("affiliation", "").strip() for a in au if a.get("affiliation", "").strip()]
        if aff:
            out.append('<div class="p-affil">' + "<br>".join(html.escape(x) for x in dict.fromkeys(aff)) + "</div>")
    if paper.get("abstract"):
        out.append('<section class="p-abstract" data-part="abstract"><span class="p-abstract-h">Abstract.</span> '
                   + tex_to_html(paper["abstract"], ctx, inline=True) + "</section>")
    meta = []
    if paper.get("keywords"):
        meta.append("<span><b>Keywords.</b> " + html.escape(", ".join(paper["keywords"])) + "</span>")
    if paper.get("msc"):
        meta.append("<span><b>MSC 2020.</b> " + html.escape(", ".join(paper["msc"])) + "</span>")
    if meta:
        out.append('<div class="p-meta">' + "".join(meta) + "</div>")
    if paper.get("intro"):
        out.append('<h2 class="p-sec" id="sec-intro"><span class="num">1.</span> Introduction</h2>')
        out.append('<div class="p-block" data-part="intro">' + tex_to_html(paper["intro"], ctx) + "</div>")
    for b in paper.get("blocks", []):
        bid = html.escape(b.get("id", ""))
        anchor = f' id="lbl-{html.escape(b["label"])}"' if b.get("label") else ""
        t = b["type"]
        if t == "section":
            out.append(f'<h2 class="p-sec" data-block="{bid}"{anchor}><span class="num">{b.get("num", "")}.</span> '
                       f'{tex_to_html(b["title"], ctx, inline=True)}</h2>')
        elif t == "subsection":
            out.append(f'<h3 class="p-subsec" data-block="{bid}"{anchor}><span class="num">{b.get("num", "")}.</span> '
                       f'{tex_to_html(b["title"], ctx, inline=True)}</h3>')
        elif t == "env":
            name = THEOREM_ENVS.get(b["env"], b["env"].capitalize())
            style = "plain" if b["env"] in _PLAIN else ("defn" if b["env"] in _DEFN else "rem")
            title = f' <span class="thm-note">({tex_to_html(b["title"], ctx, inline=True)})</span>' if b.get("title") else ""
            body = tex_to_html(b["text"], ctx)
            head = f'<span class="thm-head">{name} {b.get("num", "")}{title}.</span> '
            body = body.replace("<p>", "<p>" + head, 1) if body.startswith("<p>") else "<p>" + head + "</p>" + body
            out.append(f'<div class="p-block thm {style}" data-block="{bid}"{anchor}>{body}</div>')
        elif t == "proof":
            title = tex_to_html(b["title"], ctx, inline=True) if b.get("title") else "Proof"
            body = tex_to_html(b["text"], ctx)
            head = f'<span class="proof-head">{title}.</span> '
            body = body.replace("<p>", "<p>" + head, 1) if body.startswith("<p>") else "<p>" + head + "</p>" + body
            out.append(f'<div class="p-block proof" data-block="{bid}">{body}<span class="qed">□</span></div>')
        elif t == "figure":
            out.append(f'<div class="p-block fignote" data-block="{bid}"><span class="fig-head">Figure in the notes.</span> '
                       f'{tex_to_html(b["text"], ctx, inline=True)}</div>')
        else:
            out.append(f'<div class="p-block" data-block="{bid}">{tex_to_html(b["text"], ctx)}</div>')
    for head, text in statement_sections(paper):
        out.append(f'<h2 class="p-sec p-stmt-h">{html.escape(head)}</h2><div class="p-block p-stmt"><p>{html.escape(text)}</p></div>')
    if refs:
        out.append('<h2 class="p-sec p-refs-h">References</h2><ol class="p-refs">')
        out += [reference_html(p, ref_labels[i]) for i, p in enumerate(refs)]
        out.append("</ol>")
    out.append("</article>")
    return "\n".join(out)


